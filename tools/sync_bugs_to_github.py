def _extract_bundle_side_user_error_key(bundle: Dict[str, Any], side: str) -> Optional[str]:
    """Extract UserError key strictly from either the 'macho' or 'client' error payload."""
    manual = bundle.get("manual_report") or {}
    if side == "macho":
        fields = (
            bundle.get("summary"),
            manual.get("description"),
            bundle.get("action_error"),
            bundle.get("title"),
            manual.get("title"),
        )
        for field in fields:
            key = extract_user_error_key(field)
            if key:
                return key
        return None

    fields = (
        _get_bundle_trace(bundle),
        bundle.get("traceback"),
        bundle.get("summary"),
        manual.get("description"),
        bundle.get("title"),
        manual.get("title"),
    )
    for field in fields:
        key, non_ue = _inspect_client_text_for_user_error(field)
        if key:
            return key
        if non_ue:
            return None
    return None


def _dedup_same_step_macho_client_bundles(
    loaded_bundles: List[Tuple[str, Dict[str, Any]]],
) -> Tuple[List[Tuple[str, Dict[str, Any]]], Dict[int, List[Tuple[str, Dict[str, Any]]]]]:
    """Absorb pre-queued client-python UserError bundles into matching same-step macho bundles."""
    macho_index: Dict[Tuple[Any, str], List[Dict[str, Any]]] = {}
    for _, bundle in loaded_bundles:
        step = bundle.get("step")
        if step is None or not _is_macho_protocol_bundle(bundle):
            continue
        key = _extract_bundle_side_user_error_key(bundle, "macho")
        if key:
            macho_index.setdefault((step, key.lower()), []).append(bundle)

    if not macho_index:
        return loaded_bundles, {}

    kept: List[Tuple[str, Dict[str, Any]]] = []
    absorbed_by_macho_id: Dict[int, List[Tuple[str, Dict[str, Any]]]] = {}
    for filepath, bundle in loaded_bundles:
        step = bundle.get("step")
        absorbed_target: Optional[Dict[str, Any]] = None
        if step is not None and _is_client_traceback_bundle(bundle) and not _is_macho_protocol_bundle(bundle):
            c_key = _extract_bundle_side_user_error_key(bundle, "client")
            if c_key:
                c_head = str(bundle.get("git_head") or "").strip()
                for cand in macho_index.get((step, c_key.lower()), ()):
                    m_head = str(cand.get("git_head") or "").strip()
                    if c_head and m_head and c_head != m_head:
                        continue
                    absorbed_target = cand
                    break

        if absorbed_target is not None:
            m_manual = absorbed_target.get("manual_report") if isinstance(absorbed_target.get("manual_report"), dict) else None
            c_manual = bundle.get("manual_report") if isinstance(bundle.get("manual_report"), dict) else {}
            m_summary = str(absorbed_target.get("summary") or (m_manual.get("description") if m_manual else "") or "")
            c_summary = str(bundle.get("summary") or c_manual.get("description") or "")
            c_trace = _get_bundle_trace(bundle) or str(bundle.get("traceback") or "")
            merged_summary, merged_trace = merge_macho_client_user_error_fields(
                m_summary,
                _get_bundle_trace(absorbed_target),
                c_summary,
                c_trace,
                c_key or "",
            )
            absorbed_target["summary"] = merged_summary
            if m_manual is not None:
                m_manual["description"] = merged_summary
            if merged_trace:
                absorbed_target["trace"] = merged_trace
                absorbed_target["traceback"] = merged_trace
            alias_list = absorbed_target.setdefault("alias_hashes", [])
            if isinstance(alias_list, list) and classify_environment_fault(bundle) is None:
                eff_c_hash = _effective_bundle_hash(bundle)
                if eff_c_hash not in alias_list:
                    alias_list.append(eff_c_hash)
                try:
                    raw_c_hash = int(bundle.get("stack_hash", 0))
                except (TypeError, ValueError):
                    raw_c_hash = 0
                if raw_c_hash and raw_c_hash not in alias_list:
                    alias_list.append(raw_c_hash)
            absorbed_by_macho_id.setdefault(id(absorbed_target), []).append((filepath, bundle))
        else:
            kept.append((filepath, bundle))

    return kept, absorbed_by_macho_id


def _normalize_exception_message(msg: str) -> str:
    collapsed = " ".join(msg.split())
    return re.sub(r"0x[0-9a-fA-F]+", "0xADDR", collapsed)


def classify_environment_fault(bundle: Dict[str, Any]) -> Optional[Tuple[str, str, str]]:
    """
    Classifies environment/configuration faults that should collapse into one shared issue:
      1. Client vs server build mismatch seen in handshake.
      2. Zero requests of the reporting session reached the server.
      3. Zero public-gateway / Quasar requests reached the server (#1096..#1118 style).
    Returns `(fault_kind, fingerprint, human_summary)` or `None`.
    """
    build_info = _extract_build_info(bundle)
    if build_info["mismatch"]:
        c = build_info["client_build"] or "unknown"
        s = build_info["server_build"] or "unknown"
        return (
            "build_mismatch",
            f"env:build_mismatch:client={c}:server={s}",
            f"Client/server build mismatch (client={c}, server={s})",
        )

    req_counts = _extract_session_request_counts(bundle)
    trace = _get_bundle_trace(bundle).strip()
    is_non_python_manual = is_manual_report(bundle) and not _is_client_python_manual(bundle)
    has_error_signal = (
        not is_non_python_manual
        and (
            req_counts["server_requests_explicit"]
            or bool(trace)
            or bundle.get("report_source") == "exception"
            or _is_client_python_manual(bundle)
        )
    )
    if req_counts["server_requests"] == 0 and not req_counts["reached_server"] and has_error_signal:
        return (
            "zero_server_requests",
            "env:zero_server_requests",
            "Zero server requests reached server",
        )

    if (
        req_counts["gateway_requests"] == 0
        and not req_counts["reached_gateway"]
        and _is_gateway_failure_bundle(bundle)
    ):
        return (
            "zero_gateway_requests",
            "env:zero_gateway_requests",
            "Zero gateway requests reached server (misconfigured gateway)",
        )

    return None


def build_issue_title_and_labels(bundle: Dict[str, Any]) -> Tuple[str, List[str]]:
    env_fault = classify_environment_fault(bundle)
    if env_fault is not None:
        _, _, summary = env_fault
        title = f"[Environment] {summary}"
        labels = ["bug", "environment"]
        if len(title) > 100:
            title = title[:97] + "..."
        return title, labels

    if is_manual_report(bundle):
        manual = bundle.get("manual_report") or {}
        cat = (manual.get("category_id") or "Gameplay").strip()
        summary = (manual.get("title") or "Untitled Bug Report").strip()
        title = f"[Bug Report][{cat}] {summary}"
        labels = ["bug", "player-reported"]
    else:
        trace = _get_bundle_trace(bundle)
        stack_key = bundle.get("stack_key", "")
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        title = (
            f"[Client Crash] {exc_class}: {msg[:60]}"
            if msg
            else f"[Client Crash] {exc_class} in {location}"
        )
        labels = ["bug", "client-crash", "auto-reported"]

    if len(title) > 100:
        title = title[:97] + "..."
    return title, labels


def _compact_bundle_for_raw_json(bundle: Dict[str, Any]) -> Dict[str, Any]:
    """Summarizes bulky fields already rendered in dedicated Markdown sections above."""
    compact: Dict[str, Any] = {}
    for k, v in bundle.items():
        if k == "trace" and isinstance(v, str) and len(v) > 512:
            compact[k] = f"<omitted: {len(v)} chars rendered in Client Python Traceback above>"
        elif k in ("flight_recorder", "server_logs_before", "server_logs_after") and isinstance(v, list):
            compact[k] = f"<omitted: {len(v)} entries rendered above>"
        elif k == "manual_report" and isinstance(v, dict):
            mc = dict(v)
            for mk in ("client_logs_tail", "computer_info", "ship_fitting_eft"):
                mv = mc.get(mk)
                if isinstance(mv, list):
                    mc[mk] = f"<omitted: {len(mv)} lines rendered above>"
                elif isinstance(mv, str) and len(mv) > 512:
                    mc[mk] = f"<omitted: {len(mv)} chars rendered above>"
            compact[k] = mc
        else:
            compact[k] = v
    return compact


def _cap_markdown_body(body: str, limit: int = MAX_GITHUB_BODY_CHARS) -> str:
    """Final safety guard ensuring body never exceeds GitHub's 65,536-character API limit."""
    if len(body) <= limit:
        return body
    suffix = (
        "\n\n```\n</details>\n\n---\n"
        "*[Truncated to fit GitHub's 65,536-character issue body limit; "
        "full diagnostic bundle is preserved locally in `.evomu-bugs/`.]*"
    )
    return body[: max(0, limit - len(suffix))] + suffix


def _render_markdown_issue(
    bundle: Dict[str, Any],
    occurrences: int,
    compact_raw_json: bool = False,
    trim_sections: bool = False,
) -> str:
    trace = _get_bundle_trace(bundle).strip()
    if trim_sections and len(trace) > 14_000:
        trace = (
            trace[:4_000]
            + "\n# ... [middle of traceback truncated to fit GitHub body limit] ...\n"
            + trace[-9_500:]
        )
    stack_key = bundle.get("stack_key", "")
    stack_hash = _effective_bundle_hash(bundle)
    legacy_hashes = _legacy_client_stack_hashes(bundle, effective_hash=stack_hash)
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    sec_status = session.get("security_status")
    sec_str = f" ({sec_status:+.1f})" if isinstance(sec_status, (int, float)) else ""
    ship_name = session.get("ship_type_name") or f"Ship #{session.get('ship_type_id', 'unknown')}"

    station_id = session.get("station_id")
    structure_id = session.get("structure_id")
    coords = session.get("coordinates")
    if station_id:
        location_desc = f"Docked at NPC Station #{station_id}"
    elif structure_id:
        location_desc = f"Docked at Upwell Structure #{structure_id}"
    elif coords:
        location_desc = (
            f"In space at `({coords.get('x', 0):.0f}, {coords.get('y', 0):.0f}, {coords.get('z', 0):.0f})`"
        )
    else:
        location_desc = "Unknown location"

    flight_recorder = list(bundle.get("flight_recorder", []))
    logs_before = list(bundle.get("server_logs_before", []))
    logs_after = list(bundle.get("server_logs_after", []))
    if trim_sections:
        if len(flight_recorder) > 40:
            flight_recorder = flight_recorder[-40:]
        if len(logs_before) > 80:
            logs_before = [f"# ... [{len(logs_before) - 80} earlier log lines omitted] ..."] + logs_before[-80:]
        if len(logs_after) > 40:
            logs_after = logs_after[:40] + [f"# ... [{len(logs_after) - 40} trailing log lines omitted] ..."]

    manual = bundle.get("manual_report") if is_manual_report(bundle) else None
    req_counts = _extract_session_request_counts(bundle)
    build_info = _extract_build_info(bundle)
    env_fault = classify_environment_fault(bundle)

    sig_line = f"**Signature Hash:** `0x{unsigned_hash:016x}` (or `{stack_hash}`)"
    if legacy_hashes:
        raw_unsigned = legacy_hashes[0] & 0xFFFFFFFFFFFFFFFF
        sig_line += f" | **Client Stack Hash:** `0x{raw_unsigned:016x}`"
    sig_line += f" | **Occurrences Captured:** `{occurrences}`"

    body_lines = [
        sig_line,
        f"**Reported At:** `{timestamp}` | **Stack Key:** `{stack_key}`",
    ]
    telemetry_parts = [
        f"**Session Server Requests:** `{req_counts['server_requests']}`",
        f"**Gateway Requests:** `{req_counts['gateway_requests']}`",
    ]
    if build_info["client_build"] is not None:
        telemetry_parts.append(f"**Handshake Client Build:** `{build_info['client_build']}`")
    if build_info["server_build"] is not None:
        telemetry_parts.append(f"**Server Build:** `{build_info['server_build']}`")
    body_lines.append(" | ".join(telemetry_parts))

    if env_fault:
        fault_kind, fault_fp, fault_summary = env_fault
        body_lines.append(
            f"**Environment Fault:** `{fault_kind}` (`{fault_fp}`) — {fault_summary}"
        )

    if manual:
        report_key = manual.get("report_key") or "unknown"
        cat_name = manual.get("category_name") or manual.get("category_id") or "Gameplay"
        cat_id = manual.get("category_id") or "Gameplay"
        build_num = manual.get("client_build")
        build_str = f" | **Client Build:** `{build_num}`" if build_num is not None else ""
        body_lines.append(
            f"**Report Key:** `{report_key}` | **Category:** `{cat_name}` (`{cat_id}`){build_str}"
        )

    body_lines.extend([
        f"**Pilot:** `{char_name}` (ID: `{session.get('character_id')}`) | **System:** `{system_name}`{sec_str}",
        f"**Location:** {location_desc} | **Ship Hull:** `{ship_name}`",
        "",
        "---",
        "",
    ])

    if manual:
        desc = (manual.get("description") or "").strip() or "_No description provided._"
        repro = (manual.get("reproduction_steps") or "").strip()
        if trim_sections and len(desc) > 6_000:
            desc = desc[:6_000] + "\n\n_[Description truncated]_"
        if trim_sections and len(repro) > 4_000:
            repro = repro[:4_000] + "\n\n_[Steps truncated]_"
        body_lines.extend([
            "### 📝 Player Bug Report",
            "",
            desc,
            "",
        ])
        if repro:
            body_lines.extend([
                "#### Steps to Reproduce",
                "",
                repro,
                "",
            ])

        eft_fit = (manual.get("ship_fitting_eft") or "").strip()
        if trim_sections and len(eft_fit) > 3_000:
            eft_fit = eft_fit[:3_000] + "\n# [truncated]"
        if eft_fit:
            body_lines.extend([
                "<details>",
                "<summary><b>🚀 Active Ship EFT Fitting (from igbr.zip)</b></summary>",
                "",
                "```text",
                eft_fit,
                "```",
                "",
                "</details>",
                "",
            ])

        client_logs = list(manual.get("client_logs_tail") or [])
        if trim_sections and len(client_logs) > 60:
            client_logs = [f"... [{len(client_logs) - 60} earlier client log lines omitted] ..."] + client_logs[-60:]
        if client_logs:
            body_lines.extend([
                "<details>",
                f"<summary><b>🖥️ Client Log Tail ({len(client_logs)} lines from igbr.zip)</b></summary>",
                "",
                "```log",
                "\n".join(str(ln) for ln in client_logs),
                "```",
                "",
                "</details>",
                "",
            ])

        attachments = manual.get("attachments") or []
        if attachments:
            body_lines.append("#### 📎 Staged Local Attachments")
            body_lines.append("")
            for rel_att in attachments:
                body_lines.append(f"- `{rel_att}`")
            body_lines.append("")

        comp_info = (manual.get("computer_info") or "").strip()
        if trim_sections and len(comp_info) > 4_000:
            comp_info = comp_info[:4_000] + "\n... [truncated]"
        if comp_info:
            body_lines.extend([
                "<details>",
                "<summary><b>💻 Client Hardware & Runtime Info</b></summary>",
                "",
                "```text",
                comp_info,
                "```",
                "",
                "</details>",
                "",
            ])

    if trace or not manual:
        body_lines.extend([
            "### 🐍 Client Python Traceback",
            "```python",
            trace if trace else "# [No client traceback provided]",
            "```",
            "",
        ])

    if flight_recorder:
        label_suffix = "before report" if manual else "before crash"
        body_lines.extend([
            "<details>",
            f"<summary><b>⏱️ MachoNet RPC Flight Recorder ({len(flight_recorder)} recent calls {label_suffix})</b></summary>",
            "",
            "| Time Offset | Service | Method | Args Summary | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            args = str(call.get("args_summary", "()")).replace("|", "\\|")
            if trim_sections and len(args) > 120:
                args = args[:117] + "..."
            status = str(call.get("status", "-")).replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            body_lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{args}` | `{status}` | `{dur_str}` |")
        body_lines.extend(["", "</details>", ""])

    all_logs = []
    if logs_before:
        all_logs.append("# --- Server logs prior to report ---")
        all_logs.extend(str(ln) for ln in logs_before)
    if logs_after:
        all_logs.append("# --- Trailing server logs (+1.5s window) ---")
        all_logs.extend(str(ln) for ln in logs_after)

    if all_logs:
        body_lines.extend([
            "<details>",
            f"<summary><b>📜 Server Log Slice ({len(all_logs)} lines)</b></summary>",
            "",
            "```log",
            "\n".join(all_logs),
            "```",
            "",
            "</details>",
            "",
        ])

    raw_payload = _compact_bundle_for_raw_json(bundle) if compact_raw_json else bundle
    body_lines.extend([
        "<details>",
        "<summary><b>🔍 Raw Session & Diagnostics Metadata</b></summary>",
        "",
        "```json",
        json.dumps(raw_payload, indent=2),
        "```",
        "",
        "</details>",
        "",
        "---",
        "*Automated report generated by EvoMu In-Band Telemetry & `sync_bugs_to_github.py`.*",
    ])

    return "\n".join(body_lines)


def format_markdown_issue(bundle: Dict[str, Any], occurrences: int = 1) -> str:
    """Formats an incident bundle into GitHub Markdown bounded below GitHub's 65,536-char limit."""
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=False, trim_sections=False)
    if len(body) <= MAX_GITHUB_BODY_CHARS:
        return body
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=True, trim_sections=False)
    if len(body) <= MAX_GITHUB_BODY_CHARS:
        return body
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=True, trim_sections=True)
    return _cap_markdown_body(body, MAX_GITHUB_BODY_CHARS)


def format_occurrence_comment(bundle: Dict[str, Any], total_occurrences: int) -> str:
    """Formats an additional occurrence comment for an existing issue."""
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    flight_recorder = bundle.get("flight_recorder", [])
    manual = bundle.get("manual_report") if is_manual_report(bundle) else None
    trace = _get_bundle_trace(bundle).strip()
    stack_key = str(bundle.get("stack_key") or "")
    req_counts = _extract_session_request_counts(bundle)
    build_info = _extract_build_info(bundle)

    lines = [
        f"### 🔁 New Incident Occurrence (#{total_occurrences})",
        f"- **Timestamp:** `{timestamp}`",
        f"- **Pilot:** `{char_name}` in `{system_name}`",
        f"- **Ship:** `{session.get('ship_type_name', 'Unknown')}`",
        (
            f"- **Session Telemetry:** server_requests=`{req_counts['server_requests']}`, "
            f"gateway_requests=`{req_counts['gateway_requests']}`"
        ),
    ]
    if build_info["client_build"] is not None or build_info["server_build"] is not None:
        lines.append(
            f"- **Handshake Build:** client=`{build_info['client_build'] or 'unknown'}`, "
            f"server=`{build_info['server_build'] or 'unknown'}`"
        )
    if trace:
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        headline = f"{exc_class}: {msg[:100]}" if msg else f"{exc_class} in {location}"
        lines.append(f"- **Exception / Location:** `{headline}` (`{location}`)")
    elif stack_key:
        lines.append(f"- **Stack Key:** `{stack_key}`")

    if manual:
        if manual.get("report_key"):
            lines.append(f"- **Report Key:** `{manual['report_key']}`")
        if manual.get("description"):
            lines.extend(["", manual["description"].strip()])

    if trace:
        capped_trace = trace if len(trace) <= 12_000 else trace[:12_000] + "\n# ... [traceback truncated] ..."
        lines.extend([
            "",
            "```python",
            capped_trace,
            "```",
        ])

    if flight_recorder:
        lines.extend([
            "",
            "<details>",
            f"<summary><b>⏱️ RPC Flight Recorder ({len(flight_recorder)} calls)</b></summary>",
            "",
            "| Time Offset | Service | Method | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder[-10:]:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            status = call.get("status", "-").replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{status}` | `{dur_str}` |")
        lines.extend(["", "</details>"])

    return _cap_markdown_body("\n".join(lines), MAX_GITHUB_BODY_CHARS)


def _run_gh_with_body_file(base_cmd: List[str], body: str) -> subprocess.CompletedProcess[str]:
    """Passes Markdown body via a closed UTF-8 temp file (`--body-file`) to avoid Windows
    `CreateProcessW` 32,767-char command-line limits (`WinError 206`) and console codepage issues.
    """
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", suffix=".md", delete=False) as tf:
        tf.write(body)
        body_path = tf.name
    try:
        return subprocess.run(
            base_cmd + ["--body-file", body_path],
            check=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    finally:
        try:
            os.remove(body_path)
        except OSError:
            pass


def check_gh_installed() -> bool:
    """Checks if GitHub CLI (`gh`) is available."""
    return shutil.which("gh") is not None


def ensure_github_labels(repo: str, labels: List[str], ensured_cache: Set[str]) -> None:
    """Best-effort ensures custom labels exist in the target GitHub repository."""
    if not check_gh_installed():
        return
    for label in labels:
        if label in ensured_cache:
            continue
        color, desc = LABEL_SPECS.get(label, ("ededed", "EvoMu bug report label"))
        cmd = [
            "gh", "label", "create", label,
            "--repo", repo,
            "--color", color,
            "--description", desc,
            "--force",
        ]
        try:
            subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
        except Exception:
            pass
        ensured_cache.add(label)


def _issue_cache_key(stack_hash: int) -> str:
    return f"0x{(int(stack_hash) & 0xFFFFFFFFFFFFFFFF):016x}"


def resolve_issue_cache_path(
    queue_dir: Optional[str] = None,
    uploaded_dir: Optional[str] = None,
    cache_file: Optional[Union[str, os.PathLike[str]]] = None,
) -> Optional[Path]:
    """Resolves the persistent local hash->issue cache path for `sync_bugs_to_github.py`."""
    if cache_file is not None:
        raw = str(cache_file).strip()
        return Path(raw) if raw else None
    if queue_dir:
        q_abs = Path(os.path.abspath(queue_dir))
        if q_abs.name == "queue":
            return q_abs.parent / "issue_cache.json"
    if uploaded_dir:
        u_abs = Path(os.path.abspath(uploaded_dir))
        if u_abs.name == "uploaded":
            return u_abs.parent / "issue_cache.json"
        return u_abs / "issue_cache.json"
    if queue_dir:
        q_abs = Path(os.path.abspath(queue_dir))
        return q_abs.parent / f".{q_abs.name}_issue_cache.json"
    return None


def _load_issue_cache(cache_file: Optional[Union[str, os.PathLike[str]]]) -> Dict[str, Any]:
    if not cache_file:
        return {"repos": {}}
    path = Path(cache_file)
    if not path.exists():
        return {"repos": {}}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and isinstance(data.get("repos"), dict):
            return data
    except Exception as e:
        print(f"[warn] Ignoring unreadable issue cache '{path}': {e}", file=sys.stderr)
    return {"repos": {}}


def _save_issue_cache(cache_file: Optional[Union[str, os.PathLike[str]]], cache_data: Dict[str, Any]) -> None:
    if not cache_file:
        return
    path = Path(cache_file)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(cache_data, fh, indent=2, sort_keys=True)
        os.replace(tmp_path, path)
    finally:
        if os.path.exists(tmp_path):
            try:
                os.remove(tmp_path)
            except OSError:
                pass


def _record_issue_cache(
    cache_file: Optional[Union[str, os.PathLike[str]]],
    repo: str,
    hashes: Sequence[int],
    issue_number: int,
    state: str,
) -> None:
    if not cache_file or not hashes or int(issue_number) <= 0:
        return
    data = _load_issue_cache(cache_file)
    repos = data.setdefault("repos", {})
    repo_map = repos.setdefault(repo, {})
    norm_state = str(state or "OPEN").upper()
    now = time.time()
    for h in hashes:
        repo_map[_issue_cache_key(h)] = {
            "number": int(issue_number),
            "state": norm_state,
            "updated_at": now,
        }
    _save_issue_cache(cache_file, data)


def _lookup_issue_cache(
    cache_file: Optional[Union[str, os.PathLike[str]]],
    repo: str,
    ordered_hashes: Sequence[int],
) -> Dict[int, Tuple[int, str, int]]:
    """Returns `{issue_number: (issue_number, state, hash_rank)}` from persistent local cache."""
    if not cache_file:
        return {}
    data = _load_issue_cache(cache_file)
    repo_map = (data.get("repos") or {}).get(repo) or {}
    hits: Dict[int, Tuple[int, str, int]] = {}
    for rank, h in enumerate(ordered_hashes):
        entry = repo_map.get(_issue_cache_key(h))
        if not isinstance(entry, dict):
            continue
        try:
            num = int(entry["number"])
        except (KeyError, TypeError, ValueError):
            continue
        if num <= 0:
            continue
        state = str(entry.get("state", "OPEN")).upper()
        if num not in hits:
            hits[num] = (num, state, rank)
        else:
            prev_num, prev_state, prev_rank = hits[num]
            best_state = "OPEN" if ("OPEN" in (prev_state, state)) else state
            hits[num] = (prev_num, best_state, min(prev_rank, rank))
    return hits


_MANUAL_RECENT_TTL_SEC = 600.0
_MANUAL_SYMPTOM_KINDS = frozenset({
    "ui_state_desync",
    "broken_game_mechanic",
    "blank_or_stuck_window",
    "agent_diagnosed_bug",
})
_MANUAL_SEMANTIC_STOPWORDS = frozenset({
    "the", "a", "an", "in", "on", "at", "to", "for", "of", "by", "from", "with",
    "and", "or", "is", "are", "was", "were", "be", "been", "does", "did", "do",
    "not", "no", "after", "before", "when", "while", "into", "out", "over", "under",
    "still", "stays", "stay", "remains", "remain", "stuck", "fails", "failed", "fail",
    "instead", "without", "than", "above", "below", "wnd", "window", "dlg", "dialog",
    "panel", "modal", "button", "btn", "ui", "state", "desync", "bug", "report",
    "playtester", "broken", "game", "mechanic", "blank", "agent", "diagnosed",
})


def extract_manual_semantic_tokens(title: str) -> List[str]:
    """Extract canonical semantic content tokens from a manual bug title across LLM rephrasings."""
    s = re.sub(r"^(?:\[[^\]]+\]\s*)+", "", str(title or "").strip())
    s = re.sub(r"[_-]+", " ", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", s)
    tokens: Set[str] = set()
    for raw_tok in re.findall(r"[a-z0-9]+(?:[./][a-z0-9]+)*", s.lower()):
        tok = raw_tok
        if tok.isalpha() and len(tok) > 4 and tok.endswith("s") and not tok.endswith("ss"):
            tok = tok[:-1]
        if tok in _MANUAL_SEMANTIC_STOPWORDS:
            continue
        if len(tok) < 2:
            continue
        tokens.add(tok)
    return sorted(tokens)


def manual_semantic_group(subsystem: str, kind: str, action_error: str = "") -> str:
    sub = (subsystem or "").strip().lower() or "client-ui"
    k = (kind or "").strip().lower()
    k_group = "manual_symptom" if k in _MANUAL_SYMPTOM_KINDS else k
    err_norm = (action_error or "").strip().lower()[:80]
    return f"{sub}:{k_group}:{err_norm}"


def manual_semantic_match(tokens_a: Sequence[str], tokens_b: Sequence[str]) -> bool:
    """Return True when two manual titles in the same semantic group describe the same UI/game symptom."""
    set_a = set(tokens_a or ())
    set_b = set(tokens_b or ())
    if not set_a or not set_b:
        return False
    inter = len(set_a & set_b)
    min_len = min(len(set_a), len(set_b))
    union = len(set_a | set_b)
    if inter < 3:
        return False
    if inter < 4 and min_len > 4:
        return False
    jaccard = inter / float(union)
    overlap = inter / float(min_len)
    return jaccard >= 0.55 or (inter >= 4 and overlap >= 0.75)


def _bundle_manual_semantic_sig(bundle: Dict[str, Any]) -> Optional[Tuple[str, List[str]]]:
    if not is_manual_report(bundle):
        return None
    if _get_bundle_trace(bundle).strip():
        return None
    manual = bundle.get("manual_report") or {}
    subsystem = str(manual.get("category_id") or bundle.get("subsystem") or "client-ui")
    kind = str(manual.get("category_name") or bundle.get("kind") or "").strip().lower()
    if kind not in _MANUAL_SYMPTOM_KINDS:
        return None
    title = str(manual.get("title") or bundle.get("title") or "")
    action_err = str(bundle.get("action_error") or "")
    tokens = extract_manual_semantic_tokens(title)
    if len(tokens) < 3:
        return None
    return manual_semantic_group(subsystem, kind, action_err), tokens


def _lookup_recent_manual_issue(
    cache_file: Optional[Union[str, os.PathLike[str]]],
    repo: str,
    sig: Tuple[str, List[str]],
    now: Optional[float] = None,
) -> Optional[Tuple[int, str]]:
    """Find an open issue recently created for a semantically matching non-traceback F12 report."""
    if not cache_file:
        return None
    group, tokens = sig
    cur_now = float(now if now is not None else time.time())
    data = _load_issue_cache(cache_file)
    entries = (data.get("manual_recent") or {}).get(repo) or []
    best: Optional[Tuple[float, int, str]] = None
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        if entry.get("group") != group:
            continue
        try:
            updated_at = float(entry.get("updated_at") or 0.0)
            num = int(entry.get("number") or 0)
        except (TypeError, ValueError):
            continue
        if num <= 0 or (cur_now - updated_at) > _MANUAL_RECENT_TTL_SEC:
            continue
        state = str(entry.get("state") or "OPEN").upper()
        if state != "OPEN":
            continue
        if manual_semantic_match(entry.get("tokens") or (), tokens):
            cand = (-updated_at, num, state)
            if best is None or cand < best:
                best = cand
    if best is None:
        return None
    return best[1], best[2]


def _record_recent_manual_issue(
    cache_file: Optional[Union[str, os.PathLike[str]]],
    repo: str,
    sig: Tuple[str, List[str]],
    issue_number: int,
    state: str,
    now: Optional[float] = None,
) -> None:
    if not cache_file or int(issue_number) <= 0:
        return
    group, tokens = sig
    cur_now = float(now if now is not None else time.time())
    data = _load_issue_cache(cache_file)
    recent_by_repo = data.setdefault("manual_recent", {})
    entries = [
        e
        for e in (recent_by_repo.get(repo) or [])
        if isinstance(e, dict)
        and (cur_now - float(e.get("updated_at") or 0.0)) <= _MANUAL_RECENT_TTL_SEC
    ]
    entries.append({
        "number": int(issue_number),
        "state": str(state or "OPEN").upper(),
        "group": group,
        "tokens": list(tokens),
        "updated_at": cur_now,
    })
    recent_by_repo[repo] = entries[-200:]
    _save_issue_cache(cache_file, data)


@contextlib.contextmanager
def _sync_lock(lock_path: Optional[Path]) -> Iterator[None]:
    """Cross-platform advisory file lock (POSIX fcntl, Windows msvcrt, or exclusive lockfile)."""
    if lock_path is None:
        yield
        return
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    if fcntl is not None:
        with open(lock_path, "a+", encoding="utf-8") as lock_fh:
            fcntl.flock(lock_fh.fileno(), fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(lock_fh.fileno(), fcntl.LOCK_UN)
        return
    if msvcrt is not None:
        with open(lock_path, "a+b") as lock_fh:
            lock_fh.seek(0, os.SEEK_END)
            if lock_fh.tell() == 0:
                lock_fh.write(b"\0")
                lock_fh.flush()
            lock_fh.seek(0)
            msvcrt.locking(lock_fh.fileno(), msvcrt.LK_LOCK, 1)
            try:
                yield
            finally:
                lock_fh.seek(0)
                msvcrt.locking(lock_fh.fileno(), msvcrt.LK_UNLCK, 1)
        return

    # Pure-Python atomic O_CREAT|O_EXCL fallback if neither fcntl nor msvcrt is available.
    deadline = time.monotonic() + 60.0
    fd: Optional[int] = None
    while True:
        try:
            fd = os.open(str(lock_path), os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            os.write(fd, f"{os.getpid()}\n".encode("ascii", "replace"))
            os.close(fd)
            fd = None
            break
        except FileExistsError:
            if time.monotonic() >= deadline:
                raise TimeoutError(f"Timed out waiting for sync lock '{lock_path}'")
            try:
                st = os.stat(lock_path)
                if (time.time() - st.st_mtime) > 300.0:
                    os.remove(lock_path)
                    continue
            except OSError:
                pass
            time.sleep(0.05)
    try:
        yield
    finally:
        if fd is not None:
            try:
                os.close(fd)
            except OSError:
                pass
        try:
            os.remove(lock_path)
        except OSError:
            pass


def find_existing_issue(
    repo: str,
    stack_hash: int,
    dry_run: bool = False,
    alias_hashes: Optional[Sequence[int]] = None,
    cache_file: Optional[Union[str, os.PathLike[str]]] = None,
    cache_hashes: Optional[Sequence[int]] = None,
) -> Optional[Tuple[int, str]]:
    """
    Queries GitHub CLI (and local cache for search-lag resilience) to check if an
    issue for `stack_hash` or any legacy alias hash already exists.

    Only canonical signature hashes (`[stack_hash]` by default, or explicit `cache_hashes`)
    are read from or written to `cache_file` so non-unique raw client `stack_hash` aliases
    can never poison persistent cache lookups across unrelated crashes.

    Fails closed (`IssueLookupError`) when `gh` is unavailable or `gh issue list` errors,
    and always prefers `OPEN` issues over `CLOSED` issues.
    """
    if dry_run:
        return None
    if not check_gh_installed():
        raise IssueLookupError("GitHub CLI ('gh') is not available; failing closed to avoid duplicate issues.")

    ordered_hashes = [stack_hash, *_merge_unique_hashes(alias_hashes, exclude=stack_hash)]
    search_specs: List[Tuple[int, str]] = []
    for rank, h in enumerate(ordered_hashes):
        h_unsigned = h & 0xFFFFFFFFFFFFFFFF
        search_specs.append((rank, f'"**Signature Hash:** `0x{h_unsigned:016x}`" in:body'))
        search_specs.append((rank, f'"(or `{h}`)" in:body'))

    lookup_hashes = list(cache_hashes) if cache_hashes is not None else [stack_hash]
    if stack_hash not in lookup_hashes:
        lookup_hashes.insert(0, stack_hash)
    cached_by_num = _lookup_issue_cache(cache_file, repo, lookup_hashes)
    github_candidates: Dict[int, Tuple[int, str, int, int]] = {}
    seq = 0
    for rank, term in search_specs:
        cmd = [
            "gh", "issue", "list",
            "--repo", repo,
            "--state", "all",
            "--search", term,
            "--json", "number,title,state",
            "--limit", "20",
        ]
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=True)
            issues = json.loads(res.stdout.strip() or "[]")
            if not isinstance(issues, list):
                raise ValueError(f"Expected JSON list from gh issue list, got {type(issues).__name__}")
        except Exception as e:
            raise IssueLookupError(f"Failed to query gh for {term}: {e}") from e

        found_open = False
        for issue in issues:
            if not isinstance(issue, dict) or "number" not in issue:
                continue
            num = int(issue["number"])
            state = str(issue.get("state", "OPEN")).upper()
            if state == "OPEN":
                found_open = True
            if num not in github_candidates:
                github_candidates[num] = (num, state, rank, seq)
                seq += 1
            else:
                prev_num, prev_state, prev_rank, prev_seq = github_candidates[num]
                merged_state = "OPEN" if ("OPEN" in (prev_state, state)) else state
                github_candidates[num] = (prev_num, merged_state, min(prev_rank, rank), prev_seq)
        # Once we have an OPEN GitHub match and no higher-priority primary cache entry could beat it,
        # we can stop issuing additional legacy alias searches.
        if found_open and (
            rank == 0 or not any(c_state == "OPEN" and c_rank < rank for _, c_state, c_rank in cached_by_num.values())
        ):
            break

    merged: List[Tuple[int, int, int, int, str]] = []
    seen_nums: Set[int] = set()
    for num, state, rank, cseq in github_candidates.values():
        seen_nums.add(num)
        state_pri = 0 if state == "OPEN" else 1
        merged.append((state_pri, rank, cseq, num, state))
    for num, (_, state, rank) in cached_by_num.items():
        if num in seen_nums:
            continue
        state_pri = 0 if state == "OPEN" else 1
        merged.append((state_pri, rank, 1_000_000 + num, num, state))

    if not merged:
        return None
    merged.sort()
    _, _, _, best_num, best_state = merged[0]
    if cache_file and best_num in github_candidates:
        _record_issue_cache(cache_file, repo, lookup_hashes, best_num, best_state)
    return best_num, best_state


def _effective_bundle_hash(bundle: Dict[str, Any]) -> int:
    stack_hash = int(bundle.get("stack_hash", 0))
    stack_key = str(bundle.get("stack_key", ""))
    trace = _get_bundle_trace(bundle)

    env_fault = classify_environment_fault(bundle)
    if env_fault is not None:
        _, fingerprint, _ = env_fault
        return _fnv1a_i64(fingerprint)

    if _is_client_python_exception_bundle(bundle):
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        if exc_class != "UnknownException":
            norm_msg = _normalize_exception_message(msg)
            return _fnv1a_i64(f"client-python-exc:{exc_class}:{location}:{norm_msg}")

    if stack_hash == -1040548311 or "MollycoddledUthread" in stack_key:
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        base_hash = -1040548311 if "MollycoddledUthread" in stack_key else stack_hash
        return _fnv1a_i64(f"{base_hash}:{location}:{exc_class}:{msg}")
    return stack_hash


def _legacy_client_stack_hashes(
    bundle: Dict[str, Any],
    effective_hash: Optional[int] = None,
) -> List[int]:
    """Returns distinct legacy hashes for dedup against issues opened under older hash schemes."""
    if classify_environment_fault(bundle) is not None:
        return []
    eff = effective_hash if effective_hash is not None else _effective_bundle_hash(bundle)
    stack_key = str(bundle.get("stack_key", ""))
    trace = _get_bundle_trace(bundle)
    aliases: List[int] = []

    raw_hash: Optional[int]
    try:
        raw_hash = int(bundle.get("stack_hash", 0))
    except (TypeError, ValueError):
        raw_hash = None

    if "MollycoddledUthread" not in stack_key and raw_hash is not None and raw_hash not in (0, -1040548311):
        aliases.append(raw_hash)

    if _is_client_python_exception_bundle(bundle):
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        if exc_class != "UnknownException":
            norm_msg = _normalize_exception_message(msg)
            if msg != norm_msg:
                aliases.append(_fnv1a_i64(f"client-python-exc:{exc_class}:{location}:{msg}"))
    if "MollycoddledUthread" in stack_key and raw_hash is not None and raw_hash not in (0, -1040548311):
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        aliases.append(_fnv1a_i64(f"{raw_hash}:{location}:{exc_class}:{msg}"))

    for extra_key in ("legacy_stack_hashes", "alias_hashes"):
        extra_vals = bundle.get(extra_key)
        if isinstance(extra_vals, list):
            for v in extra_vals:
                try:
                    iv = int(v)
                except (TypeError, ValueError):
                    continue
                if iv not in (0, -1040548311):
                    aliases.append(iv)

    return _merge_unique_hashes(aliases, exclude=eff)


def _post_issue_comment_with_state(
    repo: str,
    issue_number: int,
    existing_state: str,
    comment_body: str,
    dry_run: bool = False,
) -> Tuple[bool, str]:
    """Posts an occurrence comment to an existing issue (reopening if closed). Returns `(ok, resultant_state)`."""
    if dry_run:
        if existing_state == "CLOSED":
            print(f"[dry-run] Would reopen closed issue #{issue_number}")
        preview = comment_body if len(comment_body) <= 2000 else comment_body[:2000] + "..."
        print(f"[dry-run] Would post comment to #{issue_number}:\n{preview}\n")
        return True, "OPEN" if existing_state == "CLOSED" else str(existing_state or "OPEN").upper()

    result_state = str(existing_state or "OPEN").upper()
    if result_state == "CLOSED":
        try:
            subprocess.run(
                ["gh", "issue", "reopen", str(issue_number), "--repo", repo],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=True,
            )
            result_state = "OPEN"
            print(f"[+] Reopened closed issue #{issue_number} due to new occurrence")
        except Exception as e:
            err_msg = getattr(e, "stderr", None) or str(e)
            print(f"[warn] Failed to reopen issue #{issue_number}: {err_msg}", file=sys.stderr)

    cmd = [
        "gh", "issue", "comment",
        str(issue_number),
        "--repo", repo,
    ]
    try:
        _run_gh_with_body_file(cmd, comment_body)
        print(f"[+] Added incident occurrence comment to issue #{issue_number}")
        return True, result_state
    except Exception as e:
        err_msg = getattr(e, "stderr", None) or str(e)
        print(f"[error] Failed to comment on issue #{issue_number}: {err_msg}", file=sys.stderr)
        return False, result_state


def _post_issue_comment(
    repo: str,
    issue_number: int,
    existing_state: str,
    comment_body: str,
    dry_run: bool = False,
) -> bool:
    """Posts an occurrence comment to an existing issue (reopening if closed)."""
    ok, _ = _post_issue_comment_with_state(repo, issue_number, existing_state, comment_body, dry_run=dry_run)
    return ok


def _merge_unique_hashes(*hash_groups: Optional[Sequence[int]], exclude: Optional[int] = None) -> List[int]:
    merged: List[int] = []
    seen: Set[int] = set()
    if exclude is not None:
        seen.add(exclude)
    for group in hash_groups:
        if not group:
            continue
        for val in group:
            if val not in seen:
                seen.add(val)
                merged.append(val)
    return merged


def create_or_update_issue(
    repo: str,
    bundle: Dict[str, Any],
    occurrences: int = 1,
    ensured_labels: Optional[Set[str]] = None,
    dry_run: bool = False,
    alias_hashes: Optional[Sequence[int]] = None,
    cache_file: Optional[Union[str, os.PathLike[str]]] = None,
) -> Optional[int]:
    """Creates a new issue or comments on an existing one (reopening if closed)."""
    if is_benign_client_traceback_bundle(bundle):
        print("[info] Suppressing known benign client UI traceback; skipping GitHub sync.")
        return None
    if ensured_labels is None:
        ensured_labels = set()
    stack_hash = _effective_bundle_hash(bundle)
    resolved_aliases = _merge_unique_hashes(
        _legacy_client_stack_hashes(bundle, effective_hash=stack_hash),
        alias_hashes,
        exclude=stack_hash,
    )
    canonical_hashes = [stack_hash]
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    title, labels = build_issue_title_and_labels(bundle)

    manual_sig = _bundle_manual_semantic_sig(bundle)
    existing = find_existing_issue(
        repo,
        stack_hash,
        dry_run=dry_run,
        alias_hashes=resolved_aliases,
        cache_file=None if dry_run else cache_file,
        cache_hashes=canonical_hashes,
    )
    matched_via_manual_recent = False
    if existing is None and manual_sig is not None and not dry_run and cache_file:
        existing = _lookup_recent_manual_issue(cache_file, repo, manual_sig)
        if existing is not None:
            matched_via_manual_recent = True

    if existing:
        existing_number, existing_state = existing
        print(f"[*] Found existing issue #{existing_number} (state={existing_state}) for hash 0x{unsigned_hash:016x}")
        comment_body = format_occurrence_comment(bundle, occurrences)
        comment_ok, result_state = _post_issue_comment_with_state(
            repo, existing_number, existing_state, comment_body, dry_run=dry_run
        )
        if comment_ok:
            if not dry_run and cache_file:
                if not matched_via_manual_recent:
                    _record_issue_cache(cache_file, repo, canonical_hashes, existing_number, result_state)
                if manual_sig is not None:
                    _record_recent_manual_issue(cache_file, repo, manual_sig, existing_number, result_state)
            return existing_number
        return None
    else:
        issue_body = format_markdown_issue(bundle, occurrences)
        if dry_run:
            print(f"[dry-run] Would create issue with title: {title} (labels: {','.join(labels)})")
            print(f"[dry-run] Body preview:\n{issue_body[:500]}...\n")
            return 999999

        ensure_github_labels(repo, labels, ensured_labels)
        cmd = [
            "gh", "issue", "create",
            "--repo", repo,
            "--title", title,
            "--label", ",".join(labels),
        ]
        try:
            res = _run_gh_with_body_file(cmd, issue_body)
        except subprocess.CalledProcessError:
            # Fallback without custom labels if the user lacks label-creation permission
            fallback_cmd = [
                "gh", "issue", "create",
                "--repo", repo,
                "--title", title,
            ]
            try:
                res = _run_gh_with_body_file(fallback_cmd, issue_body)
            except subprocess.CalledProcessError as e:
                print(f"[error] Failed to create issue: {e.stderr}", file=sys.stderr)
                return None

        output = res.stdout.strip()
        print(f"[+] Created issue: {output}")
        m = re.search(r"/issues/(\d+)", output)
        if not m:
            raise RuntimeError(f"Could not parse created issue number from gh issue create output: {output!r}")
        issue_number = int(m.group(1))
        if cache_file:
            _record_issue_cache(cache_file, repo, canonical_hashes, issue_number, "OPEN")
            if manual_sig is not None:
                _record_recent_manual_issue(cache_file, repo, manual_sig, issue_number, "OPEN")
        return issue_number


def is_safe_report_key(key: str) -> bool:
    return bool(key) and len(key) <= 64 and all(c.isalnum() or c in "-_" for c in key)


def archive_or_delete_attachments(
    queue_dir: str,
    uploaded_dir: str,
    bundle: Dict[str, Any],
    delete: bool,
) -> None:
    manual = bundle.get("manual_report")
    if not isinstance(manual, dict):
        return
    report_key = str(manual.get("report_key") or "").strip()
    if not is_safe_report_key(report_key):
        return

    src_dir = os.path.join(queue_dir, "attachments", report_key)
    if not os.path.isdir(src_dir):
        return

    if delete:
        shutil.rmtree(src_dir, ignore_errors=True)
    else:
        dest_parent = os.path.join(uploaded_dir, "attachments")
        os.makedirs(dest_parent, exist_ok=True)
        dest_dir = os.path.join(dest_parent, report_key)
        if os.path.exists(dest_dir):
            shutil.rmtree(dest_dir, ignore_errors=True)
        try:
            shutil.move(src_dir, dest_dir)
        except OSError as e:
            print(f"[warn] Could not archive attachments '{src_dir}' to '{dest_dir}': {e}", file=sys.stderr)


def _select_primary_and_extras(
    files: List[Tuple[str, Dict[str, Any]]],
) -> Tuple[Tuple[str, Dict[str, Any]], List[Tuple[str, Dict[str, Any]]]]:
    """Prefer auto-reported `[Client Crash]` over `[Bug Report][client-python]` as primary."""
    primary_idx = 0
    for idx, (_, b) in enumerate(files):
        if not is_manual_report(b):
            primary_idx = idx
            break
    primary = files[primary_idx]
    extras = [item for idx, item in enumerate(files) if idx != primary_idx]
    return primary, extras


def _should_comment_extra_bundle(
    primary_bundle: Dict[str, Any],
    extra_bundle: Dict[str, Any],
    env_fault: Optional[Tuple[str, str, str]],
) -> bool:
    if env_fault is not None:
        return True
    if is_manual_report(extra_bundle) != is_manual_report(primary_bundle):
        return True
    if _get_bundle_trace(extra_bundle).strip() != _get_bundle_trace(primary_bundle).strip():
        return True
    return False


def main(argv: Optional[List[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")

    parser = argparse.ArgumentParser(description="Sync EvoMu client bug reports from local queue to GitHub issues.")
    parser.add_argument("--queue-dir", default=".evomu-bugs/queue", help="Path to bug reports queue directory")
    parser.add_argument("--uploaded-dir", default=".evomu-bugs/uploaded", help="Path to archive uploaded bug reports")
    parser.add_argument("--repo", default="saverchenkov/EvoMu", help="GitHub repository (owner/name)")
    parser.add_argument("--cache-file", default=None, help="Path to local persistent hash->issue cache JSON ('' disables)")
    parser.add_argument("--dry-run", action="store_true", help="Print actions without modifying GitHub or files")
    parser.add_argument("--delete", action="store_true", help="Delete report files and attachments instead of archiving")
    parser.add_argument("--verbose", action="store_true", help="Enable verbose logging")

    args = parser.parse_args(argv)

    if not os.path.exists(args.queue_dir):
        print(f"[*] Queue directory '{args.queue_dir}' does not exist or is empty. No bugs to report.")
        return 0

    initial_files = sorted(glob.glob(os.path.join(args.queue_dir, "*.json")))
    if not initial_files:
        print(f"[*] No pending bug reports in '{args.queue_dir}'.")
        return 0

    eff_uploaded_dir: Optional[str] = None
    if not args.delete and not (
        args.queue_dir != parser.get_default("queue_dir")
        and args.uploaded_dir == parser.get_default("uploaded_dir")
    ):
        eff_uploaded_dir = args.uploaded_dir

    cache_path = (
        None
        if args.dry_run
        else resolve_issue_cache_path(
            queue_dir=args.queue_dir,
            uploaded_dir=eff_uploaded_dir,
            cache_file=args.cache_file,
        )
    )
    lock_path = (
        None
        if args.dry_run
        else (
            cache_path.with_suffix(".lock")
            if cache_path is not None
            else Path(os.path.abspath(args.queue_dir)) / ".sync.lock"
        )
    )

    if not args.dry_run and not args.delete:
        os.makedirs(args.uploaded_dir, exist_ok=True)

    def _dispose_processed_bundle(path: str, file_bundle: Dict[str, Any]) -> None:
        if args.dry_run:
            return
        if args.delete:
            try:
                os.remove(path)
            except OSError:
                pass
        else:
            dest = os.path.join(args.uploaded_dir, os.path.basename(path))
            try:
                shutil.move(path, dest)
            except OSError as e:
                print(f"[warn] Could not archive '{path}' to '{dest}': {e}", file=sys.stderr)
        archive_or_delete_attachments(
            args.queue_dir,
            args.uploaded_dir,
            file_bundle,
            delete=args.delete,
        )

    ensured_labels: Set[str] = set()
    success_count = 0
    failed_count = 0

    with _sync_lock(lock_path):
        json_files = sorted(glob.glob(os.path.join(args.queue_dir, "*.json")))
        if not json_files:
            print(f"[*] No pending bug reports in '{args.queue_dir}'.")
            return 0
        print(f"[*] Discovered {len(json_files)} queued incident report(s) in '{args.queue_dir}'.")

        loaded_bundles: List[Tuple[str, Dict[str, Any]]] = []
        suppressed_benign: List[Tuple[str, Dict[str, Any]]] = []
        for filepath in json_files:
            try:
                with open(filepath, "r", encoding="utf-8") as f:
                    bundle = json.load(f)
                if is_benign_client_traceback_bundle(bundle):
                    suppressed_benign.append((filepath, bundle))
                    continue
                loaded_bundles.append((filepath, bundle))
            except Exception as e:
                print(f"[warn] Skipping corrupt or unreadable file '{filepath}': {e}", file=sys.stderr)

        kept_bundles, absorbed_by_macho_id = _dedup_same_step_macho_client_bundles(loaded_bundles)
        groups: Dict[int, List[Tuple[str, Dict[str, Any]]]] = {}
        for filepath, bundle in kept_bundles:
            h = _effective_bundle_hash(bundle)
            groups.setdefault(h, []).append((filepath, bundle))

        for path, benign_bundle in suppressed_benign:
            print(f"[info] Suppressing known benign client UI traceback '{os.path.basename(path)}'.")
            _dispose_processed_bundle(path, benign_bundle)
            success_count += 1

        for stack_hash, files in groups.items():
            total_occurrences = len(files)
            group_file_count = total_occurrences + sum(
                len(absorbed_by_macho_id.get(id(b), ())) for _, b in files
            )
            unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
            (primary_path, primary_bundle), extra_files = _select_primary_and_extras(files)
            env_fault = classify_environment_fault(primary_bundle)
            group_aliases = _merge_unique_hashes(
                *(_legacy_client_stack_hashes(b, effective_hash=stack_hash) for _, b in files),
                exclude=stack_hash,
            )
            alias_suffix = (
                " [client hash: " + ", ".join(f"0x{(a & 0xFFFFFFFFFFFFFFFF):016x}" for a in group_aliases) + "]"
                if group_aliases
                else ""
            )
            print(f"[*] Processing error group 0x{unsigned_hash:016x} ({total_occurrences} occurrence(s)){alias_suffix}...")

            try:
                issue_id = create_or_update_issue(
                    args.repo,
                    primary_bundle,
                    total_occurrences,
                    ensured_labels=ensured_labels,
                    dry_run=args.dry_run,
                    alias_hashes=group_aliases,
                    cache_file=cache_path,
                )
            except Exception as e:
                print(
                    f"[error] Failed creating/updating issue for group 0x{unsigned_hash:016x}: {e}",
                    file=sys.stderr,
                )
                failed_count += group_file_count
                continue

            if not issue_id:
                print(
                    f"[error] Retaining {group_file_count} bundle(s) for group 0x{unsigned_hash:016x} because issue sync did not succeed.",
                    file=sys.stderr,
                )
                failed_count += group_file_count
                continue

            _dispose_processed_bundle(primary_path, primary_bundle)
            success_count += 1
            for abs_path, abs_bundle in absorbed_by_macho_id.get(id(primary_bundle), ()):
                _dispose_processed_bundle(abs_path, abs_bundle)
                success_count += 1

            for occ_idx, (extra_path, extra_bundle) in enumerate(extra_files, start=2):
                absorbed_extra = absorbed_by_macho_id.get(id(extra_bundle), ())
                if _should_comment_extra_bundle(primary_bundle, extra_bundle, env_fault):
                    comment_body = format_occurrence_comment(extra_bundle, occ_idx)
                    comment_ok = _post_issue_comment(
                        args.repo,
                        issue_id,
                        "OPEN",
                        comment_body,
                        dry_run=args.dry_run,
                    )
                    if not comment_ok:
                        print(
                            f"[error] Retaining '{os.path.basename(extra_path)}' in queue because commenting on #{issue_id} failed.",
                            file=sys.stderr,
                        )
                        failed_count += 1 + len(absorbed_extra)
                        continue
                _dispose_processed_bundle(extra_path, extra_bundle)
                success_count += 1
                for abs_path, abs_bundle in absorbed_extra:
                    _dispose_processed_bundle(abs_path, abs_bundle)
                    success_count += 1

    print(f"[✓] Processed {success_count}/{len(json_files)} incident file(s).")
    return 1 if failed_count > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
