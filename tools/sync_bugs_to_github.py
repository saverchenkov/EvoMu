def _fnv1a_i64(signature: str) -> int:
    """Computes a deterministic signed 64-bit FNV-1a hash matching Rust `i64` storage."""
    h = _FNV1A_OFFSET
    for b in signature.encode("utf-8", errors="replace"):
        h ^= b
        h = (h * _FNV1A_PRIME) & 0xFFFFFFFFFFFFFFFF
    if h >= (1 << 63):
        h -= 1 << 64
    return h


