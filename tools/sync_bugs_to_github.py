def _extract_balanced_tuple_repr(text: str) -> str:
    """Extracts the leading parenthesized `args=(...)` tuple before trailing `kwargs=...`."""
    if not text.startswith("("):
        return re.sub(r"\s+kwargs=.*$", "", text).strip()
    depth = 0
    quote: Optional[str] = None
    escaped = False
    for idx, ch in enumerate(text):
        if quote is not None:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = None
            continue
        if ch in ("'", '"'):
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return text[: idx + 1]
    kw_idx = text.rfind("kwargs=")
    if kw_idx != -1:
        return text[:kw_idx].strip()
    return text


def _parse_logtraceback_args(line: str, *, pattern: re.Pattern[str] = _LOG_TRACEBACK_ARGS_RE) -> str:
    m = pattern.match(line)
    if not m:
        return ""
    raw_tuple = _extract_balanced_tuple_repr(line[m.end() :].strip())
    try:
        parsed = ast.literal_eval(raw_tuple)
        if isinstance(parsed, tuple):
            return " ".join(str(x) for x in parsed if x is not None).strip()
        return str(parsed).strip()
    except Exception:
        return raw_tuple.strip("()'\" ,")


def _pick_leaf_frame(frames: List[Tuple[str, str, Optional[str]]]) -> Tuple[str, str, Optional[str]]:
    chosen = frames[-1]
    for cand in reversed(frames):
        if _strip_py_extension(cand[0]) not in _CLIENT_FRAME_WRAPPER_STEMS:
            chosen = cand
            break
    return chosen


def _extract_exception_from_lines(lines: List[str]) -> Tuple[str, str]:
    exc_class = ""
    msg = ""
    for idx, line in enumerate(lines):
        if line.startswith("Formatted exception info:"):
            rest = line[len("Formatted exception info:") :].strip()
            if not rest and idx + 1 < len(lines):
                next_line = lines[idx + 1]
                if not any(next_line.startswith(p) for p in _NOISE_LINE_PREFIXES):
                    rest = next_line
            if ":" in rest:
                exc_class, msg = rest.split(":", 1)
                exc_class, msg = exc_class.strip(), msg.strip()
            elif rest:
                exc_class = rest
            break

    if not exc_class:
        stacktrace_msg = ""
        logtraceback_msg = ""
        saw_logtraceback = False
        for line in lines:
            m_st = re.match(r"^STACKTRACE\s+#\d+(?:.*?\s:\s*|[^:]*:\s*)(.+)$", line)
            if m_st and not stacktrace_msg:
                stacktrace_msg = m_st.group(1).strip()
            if _LOG_TRACEBACK_ARGS_RE.match(line):
                saw_logtraceback = True
                if not logtraceback_msg:
                    logtraceback_msg = _parse_logtraceback_args(line)

        if logtraceback_msg:
            exc_class, msg = "LogTraceback", logtraceback_msg
        elif stacktrace_msg:
            exc_class, msg = "LogTraceback", stacktrace_msg
        elif saw_logtraceback:
            exc_class, msg = "LogTraceback", ""

    if not exc_class:
        candidate_lines: List[str] = []
        skip_next_code_line = False
        fallback_logexc_msg = ""
        saw_logexc_call = False
        for line in lines:
            if _FILE_LINE_RE.search(line):
                skip_next_code_line = True
                continue
            if any(line.startswith(p) for p in _NOISE_LINE_PREFIXES) or line in (
                "None",
                "NoneType: None",
                "{",
                "}",
            ):
                skip_next_code_line = False
                continue
            if _LOG_CALL_ARGS_RE.match(line) or _LOG_TRACEBACK_ARGS_RE.match(line):
                saw_logexc_call = True
                if not fallback_logexc_msg:
                    fallback_logexc_msg = _parse_logtraceback_args(line, pattern=_LOG_CALL_ARGS_RE)
                skip_next_code_line = False
                continue
            if line.startswith("Traceback (most recent call last):") or line.startswith(
                "logmodule.LogException Traceback"
            ):
                skip_next_code_line = False
                continue
            if line.startswith(("EXCEPTION #", "STACKTRACE #")):
                skip_next_code_line = False
                continue
            if _EVE_PRE_FRAME_RE.match(line):
                skip_next_code_line = False
                continue
            if skip_next_code_line and ":" not in line and not re.match(
                r"^[A-Za-z_][A-Za-z0-9_.]*(?:Error|Exception|Exit|Interrupt|Warning)\b", line
            ):
                skip_next_code_line = False
                continue
            skip_next_code_line = False
            candidate_lines.append(line)

        if candidate_lines:
            last_line = candidate_lines[-1]
            if ":" in last_line:
                exc_class, msg = last_line.split(":", 1)
                exc_class, msg = exc_class.strip(), msg.strip()
            else:
                exc_class = last_line.strip()
                msg = ""
        elif saw_logexc_call:
            exc_class = "LogException"
            msg = fallback_logexc_msg

    return exc_class, msg


def _extract_location_from_lines(lines: List[str]) -> Optional[str]:
    # Collect EVE `<pre>/path/file.py(123) fn` or `Traced at:` frames cleanly.
    thrown_idx = next((i for i, l in enumerate(lines) if l.startswith("Thrown at:")), None)
    traced_idx = next((i for i, l in enumerate(lines) if l.startswith("Traced at:")), None)
    in_eve_frame_block = thrown_idx is not None or traced_idx is not None
    search_start = (
        thrown_idx + 1 if thrown_idx is not None else (traced_idx + 1 if traced_idx is not None else 0)
    )
    search_lines = lines[search_start:]

    pre_frames: List[Tuple[str, str, Optional[str]]] = []
    unprefixed_pre_frames: List[Tuple[str, str, Optional[str]]] = []
    for line in search_lines:
        if line.startswith(("Formatted exception info:", "Common path prefix", "EXCEPTION END")):
            break
        if line.startswith("Traced at:") and (pre_frames or unprefixed_pre_frames):
            break
        if (
            _FILE_LINE_RE.search(line)
            or _LOG_CALL_ARGS_RE.match(line)
            or _LOG_TRACEBACK_ARGS_RE.match(line)
            or any(line.startswith(p) for p in _NOISE_LINE_PREFIXES)
            or line.startswith(("EXCEPTION #", "STACKTRACE #"))
        ):
            continue
        m_pre = _EVE_PRE_FRAME_RE.match(line)
        if m_pre:
            filepath = os.path.basename(m_pre.group(1).replace("\\", "/"))
            frame = (filepath, m_pre.group(2), m_pre.group(3))
            if in_eve_frame_block or line.startswith("<pre>"):
                pre_frames.append(frame)
            else:
                unprefixed_pre_frames.append(frame)

    if pre_frames:
        filepath, lineno, fn = _pick_leaf_frame(pre_frames)
        return f"{filepath}:{lineno} in {fn}" if fn else f"{filepath}:{lineno}"

    py_frames: List[Tuple[str, str, Optional[str]]] = []
    for line in lines:
        m = _FILE_LINE_RE.search(line)
        if m:
            filepath = os.path.basename(m.group(1).replace("\\", "/"))
            py_frames.append((filepath, m.group(2), m.group(3)))

    if py_frames:
        filepath, lineno, fn = _pick_leaf_frame(py_frames)
        return f"{filepath}:{lineno} in {fn}" if fn else f"{filepath}:{lineno}"

    if unprefixed_pre_frames:
        filepath, lineno, fn = _pick_leaf_frame(unprefixed_pre_frames)
        return f"{filepath}:{lineno} in {fn}" if fn else f"{filepath}:{lineno}"

    return None


def parse_traceback_summary(trace: str, stack_key: str) -> Tuple[str, str, str]:
    """
    Extracts (exception_class, error_msg, location) from a Python traceback,
    playtester log capture (`logmodule.LogException` / `log.LogTraceback`), or EVE
    `alert.SendClientStackTraceAlert` formatted exception block.
    """
    raw = trace.replace("\r\n", "\n").strip()
    if not raw:
        return "UnknownException", "No traceback provided", stack_key or "unknown"

    parts = _CALLSTACK_SPLIT_RE.split(raw, maxsplit=1)
    primary_lines = [line.strip() for line in parts[0].splitlines() if line.strip()]
    callstack_lines = (
        [line.strip() for line in parts[1].splitlines() if line.strip()] if len(parts) > 1 else []
    )
    all_lines = primary_lines or callstack_lines

    exc_class, msg = _extract_exception_from_lines(primary_lines)
    if not exc_class and callstack_lines:
        exc_class, msg = _extract_exception_from_lines(callstack_lines)
    if not exc_class:
        last_line = all_lines[-1]
        if ":" in last_line:
            exc_class, msg = last_line.split(":", 1)
            exc_class, msg = exc_class.strip(), msg.strip()
        else:
            exc_class, msg = last_line.strip(), ""

    clean_stack_key = stack_key.strip() if stack_key else ""
    if clean_stack_key.startswith(("Caught at:", "Thrown at:")):
        clean_stack_key = ""
    location = clean_stack_key or "unknown"

    # Prefer throw-site frames before `\nCALLSTACK:\n`, falling back to `CALLSTACK:` only when primary lacks frames.
    parsed_loc = _extract_location_from_lines(primary_lines)
    if parsed_loc is None and callstack_lines:
        parsed_loc = _extract_location_from_lines(callstack_lines)
    if parsed_loc is not None:
        location = parsed_loc

    return exc_class, msg, location


def _iter_bundle_scopes(bundle: Dict[str, Any]) -> List[Dict[str, Any]]:
    scopes: List[Dict[str, Any]] = [bundle]
    for key in ("handshake", "session", "diagnostics", "telemetry", "manual_report"):
        sub = bundle.get(key)
        if isinstance(sub, dict):
            scopes.append(sub)
    return scopes


def _coerce_request_count(val: Any) -> Optional[int]:
    if isinstance(val, bool) or val is None:
        return None
    if isinstance(val, int):
        return val
    if isinstance(val, float):
        return int(val)
    if isinstance(val, str) and val.strip().isdigit():
        return int(val.strip())
    if isinstance(val, list):
        return len(val)
    return None


def _first_present_count(scopes: List[Dict[str, Any]], keys: Tuple[str, ...]) -> Optional[int]:
    for scope in scopes:
        for key in keys:
            if key in scope and scope[key] is not None:
                count = _coerce_request_count(scope[key])
                if count is not None:
                    return count
    return None


def _normalize_build_scalar(val: Any) -> Optional[str]:
    if val is None or isinstance(val, bool):
        return None
    if isinstance(val, int):
        return str(val) if val > 0 else None
    if isinstance(val, float):
        if not (val > 0) or val != val or val == float("inf"):
            return None
        return str(int(val)) if val.is_integer() else str(val)
    s = str(val).strip()
    if not s:
        return None
    if re.fullmatch(r"[+-]?\d+", s):
        n = int(s)
        return str(n) if n > 0 else None
    return s


def _first_present_build(scopes: List[Dict[str, Any]], keys: Tuple[str, ...]) -> Optional[str]:
    for scope in scopes:
        for key in keys:
            val = _normalize_build_scalar(scope.get(key))
            if val is not None:
                return val
    return None


_GATEWAY_SERVER_STATUS_RE = re.compile(
    r"\bstatus\s*=\s*(?:2\d\d|400|401|403|404|409|422)\b", re.IGNORECASE
)
_CLIENT_TRANSPORT_FAILURE_RE = re.compile(
    r"transport|connection|refused|timed?\s*out|deadline|unavailable|channel|"
    r"socket|broken pipe|reset by peer|unreachable|\beof\b|\bdns\b|502\b|503\b|504\b",
    re.IGNORECASE,
)
_QUASAR_LOG_STARTUP_RE = re.compile(
    r"descriptor manifest|listening on|starting quasar|loaded quasar|descriptors loaded",
    re.IGNORECASE,
)


def _is_positive_identity(val: Any) -> bool:
    if isinstance(val, bool) or val is None:
        return False
    if isinstance(val, int):
        return val > 0
    if isinstance(val, str):
        s = val.strip()
        if not s or s.lower() in ("none", "null", "0"):
            return False
        if s.isdigit():
            return int(s) > 0
        return True
    return False


def _has_authenticated_session_evidence(bundle: Dict[str, Any]) -> bool:
    """Returns True when bundle session/ledger/destiny state proves the client reached eve-server."""
    session = bundle.get("session")
    if isinstance(session, dict):
        for key in ("user_id", "userid", "character_id", "charid"):
            if _is_positive_identity(session.get(key)):
                return True
    outbound = bundle.get("outbound_ledger")
    if isinstance(outbound, list) and len(outbound) > 0:
        return True
    destiny = bundle.get("destiny_stamps")
    if isinstance(destiny, list) and len(destiny) > 0:
        return True
    return False


def _is_client_transport_failure_call(call: Any) -> bool:
    """Detects client-side transport errors (e.g. refused/timed-out publicGateway) that never reached server."""
    if not isinstance(call, dict):
        return False
    if call.get("transport_error") is True or call.get("client_transport_failure") is True:
        return True
    if call.get("reached_server") is True:
        return False

    svc = str(call.get("service") or "").lower()
    explicit_err = str(call.get("error") or "").strip()
    raw_status = call.get("status")
    if raw_status is None or not str(raw_status).strip():
        status_str = f"ERR({explicit_err})" if explicit_err else "OK"
    else:
        status_str = str(raw_status).strip()
    detail_str = explicit_err or str(call.get("result") or "").strip()
    combined_status = f"{status_str} {detail_str}".strip()
    is_gateway = _is_quasar_call(call)

    if status_str.upper().startswith("OK") and not explicit_err:
        return False

    # Server-recorded gateway services only appear in FlightRecorder after hitting eve-server,
    # unless the entry carries an explicit client-side transport failure signal.
    if svc in ("quasar_grpc", "publicgatewaysvc"):
        return bool(_CLIENT_TRANSPORT_FAILURE_RE.search(combined_status))

    if is_gateway:
        return bool(
            _CLIENT_TRANSPORT_FAILURE_RE.search(combined_status)
            or not _GATEWAY_SERVER_STATUS_RE.search(combined_status)
        )

    if re.search(
        r"connection\s*refused|connection\s*reset|socket\s*error|connect\s*timeout|transport\s*closed",
        combined_status,
        re.IGNORECASE,
    ):
        return True
    return False


def _is_quasar_call(call: Dict[str, Any]) -> bool:
    kind = str(call.get("kind") or "").strip().lower()
    svc = str(call.get("service") or "").lower()
    method = str(call.get("method") or "").lower()
    return kind == "quasar" or "quasar" in svc or "gateway" in svc or "quasar" in method


def _is_gateway_flight_call_reached_server(call: Any) -> bool:
    if not isinstance(call, dict) or not _is_quasar_call(call):
        return False
    return not _is_client_transport_failure_call(call)


def _extract_session_request_counts(bundle: Dict[str, Any]) -> Dict[str, Any]:
    """Inspects session request counts reaching the server and public gateway."""
    scopes = _iter_bundle_scopes(bundle)
    explicit_server = _first_present_count(scopes, _SERVER_REQUEST_COUNT_KEYS)
    explicit_gateway = _first_present_count(scopes, _GATEWAY_REQUEST_COUNT_KEYS)

    flight_recorder = bundle.get("flight_recorder") or []
    logs_before = bundle.get("server_logs_before") or []
    logs_after = bundle.get("server_logs_after") or []
    all_logs = [str(ln) for ln in logs_before] + [str(ln) for ln in logs_after]

    observed_server = sum(
        1
        for call in flight_recorder
        if isinstance(call, dict) and not _is_client_transport_failure_call(call)
    )
    observed_gateway = sum(
        1 for call in flight_recorder if _is_gateway_flight_call_reached_server(call)
    ) + sum(
        1
        for ln in all_logs
        if re.search(
            r"eve_server::quasar_grpc|quasar_grpc::|/eve_public\.|gateway\.Requests|gateway\.Events|publicGatewaySvc",
            ln,
        )
        and not _QUASAR_LOG_STARTUP_RE.search(ln)
    )

    server_requests = max(explicit_server or 0, observed_server)
    gateway_requests = max(explicit_gateway or 0, observed_gateway)
    reached_server = (
        server_requests > 0
        or observed_server > 0
        or _has_authenticated_session_evidence(bundle)
    )
    reached_gateway = gateway_requests > 0 or observed_gateway > 0
    return {
        "server_requests": server_requests,
        "gateway_requests": gateway_requests,
        "server_requests_explicit": explicit_server is not None,
        "gateway_requests_explicit": explicit_gateway is not None,
        "reached_server": reached_server,
        "reached_gateway": reached_gateway,
    }


def _extract_build_info(bundle: Dict[str, Any]) -> Dict[str, Any]:
    """Inspects client and server build numbers reported in handshake/session metadata or logs."""
    scopes = _iter_bundle_scopes(bundle)
    client_build = _first_present_build(scopes, _CLIENT_BUILD_KEYS)
    server_build = _first_present_build(scopes, _SERVER_BUILD_KEYS)

    explicit_mismatch = any(scope.get("build_mismatch") is True for scope in scopes)
    explicit_compatible = not explicit_mismatch and any(
        scope.get("build_mismatch") is False
        and _first_present_build([scope], _CLIENT_BUILD_KEYS) is not None
        for scope in scopes
    )

    logs_and_trace = (
        [str(ln) for ln in (bundle.get("server_logs_before") or [])]
        + [str(ln) for ln in (bundle.get("server_logs_after") or [])]
        + [_get_bundle_trace(bundle)]
    )
    for text in logs_and_trace:
        if not text:
            continue
        m_boot = re.search(r"Boot Build is (\d+)\s+but should be(?:\s+at least)?\s+(\d+)", text, re.IGNORECASE)
        if m_boot:
            client_build = client_build or _normalize_build_scalar(m_boot.group(1))
            server_build = server_build or _normalize_build_scalar(m_boot.group(2))
            explicit_mismatch = True
        m_kv = re.search(
            r"client_build\s*[=:]\s*([^\s,;]+).*?(?:server_build|expected_build)\s*[=:]\s*([^\s,;]+)",
            text,
            re.IGNORECASE,
        )
        if m_kv:
            client_build = client_build or _normalize_build_scalar(m_kv.group(1))
            server_build = server_build or _normalize_build_scalar(m_kv.group(2))
        if re.search(r"Boot Build Mismatch|Handshake Failed.*Build Mismatch", text, re.IGNORECASE):
            explicit_mismatch = True

    norm_client = _normalize_build_scalar(client_build)
    norm_server = _normalize_build_scalar(server_build)
    builds_differ = (
        norm_client is not None and norm_server is not None and norm_client != norm_server
    )
    if explicit_mismatch:
        mismatch = True
    elif builds_differ and norm_client.isdigit() and norm_server.isdigit():
        mismatch = int(norm_client) < int(norm_server)
    elif explicit_compatible:
        mismatch = False
    elif builds_differ:
        mismatch = True
    else:
        mismatch = False
    return {
        "client_build": norm_client,
        "server_build": norm_server,
        "mismatch": mismatch,
    }


def _is_gateway_failure_bundle(bundle: Dict[str, Any]) -> bool:
    """Detects client failures talking to the public gateway / Quasar RPC layer."""
    trace = _get_bundle_trace(bundle)
    stack_key = str(bundle.get("stack_key") or "")
    manual = bundle.get("manual_report") if isinstance(bundle.get("manual_report"), dict) else {}
    manual_text = " ".join(
        str(manual.get(k) or "") for k in ("title", "description")
    )
    combined = "\n".join(part for part in (trace, stack_key, manual_text) if part)
    if combined:
        if re.search(r"ServerException\b|GenericInternalServerError\b|CampaignRequestError\b", combined):
            return True
        if "Could not fetch owned ship cosmetic licenses" in combined:
            return True
        if "invalid character on request" in combined and ("dispatched" in combined or "quasar" in combined.lower()):
            return True
        if "Request timed out" in combined and re.search(
            r"InternalServerError|request_messenger|quasar|gateway|PLEX", combined, re.IGNORECASE
        ):
            return True
        if re.search(
            r"(?:quasar|request_messenger)\.py|eve_public\.gateway|(?:quasar(?:_grpc)?|public\s*gateway)\b",
            combined,
            re.IGNORECASE,
        ) and re.search(r"Error|Exception|Timeout|timed out|failed|refused|unavailable", combined, re.IGNORECASE):
            return True

    for call in bundle.get("flight_recorder") or []:
        if not isinstance(call, dict) or not _is_quasar_call(call):
            continue
        status_str = str(call.get("status") or "").strip()
        if (
            _is_client_transport_failure_call(call)
            or bool(str(call.get("error") or "").strip())
            or (
                bool(status_str)
                and not status_str.upper().startswith("OK")
                and not re.search(r"\bstatus\s*=\s*2\d\d\b", status_str, re.IGNORECASE)
            )
        ):
            return True
    return False


def is_manual_report(bundle: Dict[str, Any]) -> bool:
    return bundle.get("report_source") == "f12_manual" or isinstance(bundle.get("manual_report"), dict)


def _is_client_python_manual(bundle: Dict[str, Any]) -> bool:
    if not is_manual_report(bundle):
        return False
    manual = bundle.get("manual_report") or {}
    cat = str(manual.get("category_id") or "").strip().lower()
    subsys = str(bundle.get("subsystem") or "").strip().lower()
    stack_key = str(bundle.get("stack_key") or "").strip().lower()
    return cat == "client-python" or subsys == "client-python" or stack_key.startswith("playtester:client-python:")


def _is_client_python_exception_bundle(bundle: Dict[str, Any]) -> bool:
    trace = _get_bundle_trace(bundle).strip()
    if not trace:
        return False
    if not is_manual_report(bundle):
        return True
    return _is_client_python_manual(bundle)


def _normalize_exception_message(msg: str) -> str:
    collapsed = " ".join(msg.split())
    return re.sub(r"0x[0-9a-fA-F]+", "0xADDR", collapsed)


def classify_environment_fault(bundle: Dict[str, Any]) -> Optional[Tuple[str, str, str]]:
    """
    Classifies environment/configuration faults that should collapse into one shared issue:
      1. Client vs server build mismatch seen in handshake.
      2. Zero requests of the reporting session reached the server.
      3. Zero public-gateway / Quasar requests reached the server (#1096..#1118 style).
    Returns `(fault_kind, fingerprint, human_summary)` or `None`.
    """
    build_info = _extract_build_info(bundle)
    if build_info["mismatch"]:
        c = build_info["client_build"] or "unknown"
        s = build_info["server_build"] or "unknown"
        return (
            "build_mismatch",
            f"env:build_mismatch:client={c}:server={s}",
            f"Client/server build mismatch (client={c}, server={s})",
        )

    req_counts = _extract_session_request_counts(bundle)
    trace = _get_bundle_trace(bundle).strip()
    is_non_python_manual = is_manual_report(bundle) and not _is_client_python_manual(bundle)
    has_error_signal = (
        not is_non_python_manual
        and (
            req_counts["server_requests_explicit"]
            or bool(trace)
            or bundle.get("report_source") == "exception"
            or _is_client_python_manual(bundle)
        )
    )
    if req_counts["server_requests"] == 0 and not req_counts["reached_server"] and has_error_signal:
        return (
            "zero_server_requests",
            "env:zero_server_requests",
            "Zero server requests reached server",
        )

    if (
        req_counts["gateway_requests"] == 0
        and not req_counts["reached_gateway"]
        and _is_gateway_failure_bundle(bundle)
    ):
        return (
            "zero_gateway_requests",
            "env:zero_gateway_requests",
            "Zero gateway requests reached server (misconfigured gateway)",
        )

    return None


def build_issue_title_and_labels(bundle: Dict[str, Any]) -> Tuple[str, List[str]]:
    env_fault = classify_environment_fault(bundle)
    if env_fault is not None:
        _, _, summary = env_fault
        title = f"[Environment] {summary}"
        labels = ["bug", "environment"]
        if len(title) > 100:
            title = title[:97] + "..."
        return title, labels

    if is_manual_report(bundle):
        manual = bundle.get("manual_report") or {}
        cat = (manual.get("category_id") or "Gameplay").strip()
        summary = (manual.get("title") or "Untitled Bug Report").strip()
        title = f"[Bug Report][{cat}] {summary}"
        labels = ["bug", "player-reported"]
    else:
        trace = _get_bundle_trace(bundle)
        stack_key = bundle.get("stack_key", "")
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        title = (
            f"[Client Crash] {exc_class}: {msg[:60]}"
            if msg
            else f"[Client Crash] {exc_class} in {location}"
        )
        labels = ["bug", "client-crash", "auto-reported"]

    if len(title) > 100:
        title = title[:97] + "..."
    return title, labels


def _compact_bundle_for_raw_json(bundle: Dict[str, Any]) -> Dict[str, Any]:
    """Summarizes bulky fields already rendered in dedicated Markdown sections above."""
    compact: Dict[str, Any] = {}
    for k, v in bundle.items():
        if k == "trace" and isinstance(v, str) and len(v) > 512:
            compact[k] = f"<omitted: {len(v)} chars rendered in Client Python Traceback above>"
        elif k in ("flight_recorder", "server_logs_before", "server_logs_after") and isinstance(v, list):
            compact[k] = f"<omitted: {len(v)} entries rendered above>"
        elif k == "manual_report" and isinstance(v, dict):
            mc = dict(v)
            for mk in ("client_logs_tail", "computer_info", "ship_fitting_eft"):
                mv = mc.get(mk)
                if isinstance(mv, list):
                    mc[mk] = f"<omitted: {len(mv)} lines rendered above>"
                elif isinstance(mv, str) and len(mv) > 512:
                    mc[mk] = f"<omitted: {len(mv)} chars rendered above>"
            compact[k] = mc
        else:
            compact[k] = v
    return compact


def _cap_markdown_body(body: str, limit: int = MAX_GITHUB_BODY_CHARS) -> str:
    """Final safety guard ensuring body never exceeds GitHub's 65,536-character API limit."""
    if len(body) <= limit:
        return body
    suffix = (
        "\n\n```\n</details>\n\n---\n"
        "*[Truncated to fit GitHub's 65,536-character issue body limit; "
        "full diagnostic bundle is preserved locally in `.evomu-bugs/`.]*"
    )
    return body[: max(0, limit - len(suffix))] + suffix


def _render_markdown_issue(
    bundle: Dict[str, Any],
    occurrences: int,
    compact_raw_json: bool = False,
    trim_sections: bool = False,
) -> str:
    trace = _get_bundle_trace(bundle).strip()
    if trim_sections and len(trace) > 14_000:
        trace = (
            trace[:4_000]
            + "\n# ... [middle of traceback truncated to fit GitHub body limit] ...\n"
            + trace[-9_500:]
        )
    stack_key = bundle.get("stack_key", "")
    stack_hash = bundle.get("stack_hash", 0)
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    sec_status = session.get("security_status")
    sec_str = f" ({sec_status:+.1f})" if isinstance(sec_status, (int, float)) else ""
    ship_name = session.get("ship_type_name") or f"Ship #{session.get('ship_type_id', 'unknown')}"

    station_id = session.get("station_id")
    structure_id = session.get("structure_id")
    coords = session.get("coordinates")
    if station_id:
        location_desc = f"Docked at NPC Station #{station_id}"
    elif structure_id:
        location_desc = f"Docked at Upwell Structure #{structure_id}"
    elif coords:
        location_desc = (
            f"In space at `({coords.get('x', 0):.0f}, {coords.get('y', 0):.0f}, {coords.get('z', 0):.0f})`"
        )
    else:
        location_desc = "Unknown location"

    flight_recorder = list(bundle.get("flight_recorder", []))
    logs_before = list(bundle.get("server_logs_before", []))
    logs_after = list(bundle.get("server_logs_after", []))
    if trim_sections:
        if len(flight_recorder) > 40:
            flight_recorder = flight_recorder[-40:]
        if len(logs_before) > 80:
            logs_before = [f"# ... [{len(logs_before) - 80} earlier log lines omitted] ..."] + logs_before[-80:]
        if len(logs_after) > 40:
            logs_after = logs_after[:40] + [f"# ... [{len(logs_after) - 40} trailing log lines omitted] ..."]

    manual = bundle.get("manual_report") if is_manual_report(bundle) else None
    req_counts = _extract_session_request_counts(bundle)
    build_info = _extract_build_info(bundle)
    env_fault = classify_environment_fault(bundle)

    body_lines = [
        f"**Signature Hash:** `0x{unsigned_hash:016x}` (or `{stack_hash}`) | **Occurrences Captured:** `{occurrences}`",
        f"**Reported At:** `{timestamp}` | **Stack Key:** `{stack_key}`",
    ]
    telemetry_parts = [
        f"**Session Server Requests:** `{req_counts['server_requests']}`",
        f"**Gateway Requests:** `{req_counts['gateway_requests']}`",
    ]
    if build_info["client_build"] is not None:
        telemetry_parts.append(f"**Handshake Client Build:** `{build_info['client_build']}`")
    if build_info["server_build"] is not None:
        telemetry_parts.append(f"**Server Build:** `{build_info['server_build']}`")
    body_lines.append(" | ".join(telemetry_parts))

    if env_fault:
        fault_kind, fault_fp, fault_summary = env_fault
        body_lines.append(
            f"**Environment Fault:** `{fault_kind}` (`{fault_fp}`) — {fault_summary}"
        )

    if manual:
        report_key = manual.get("report_key") or "unknown"
        cat_name = manual.get("category_name") or manual.get("category_id") or "Gameplay"
        cat_id = manual.get("category_id") or "Gameplay"
        build_num = manual.get("client_build")
        build_str = f" | **Client Build:** `{build_num}`" if build_num is not None else ""
        body_lines.append(
            f"**Report Key:** `{report_key}` | **Category:** `{cat_name}` (`{cat_id}`){build_str}"
        )

    body_lines.extend([
        f"**Pilot:** `{char_name}` (ID: `{session.get('character_id')}`) | **System:** `{system_name}`{sec_str}",
        f"**Location:** {location_desc} | **Ship Hull:** `{ship_name}`",
        "",
        "---",
        "",
    ])

    if manual:
        desc = (manual.get("description") or "").strip() or "_No description provided._"
        repro = (manual.get("reproduction_steps") or "").strip()
        if trim_sections and len(desc) > 6_000:
            desc = desc[:6_000] + "\n\n_[Description truncated]_"
        if trim_sections and len(repro) > 4_000:
            repro = repro[:4_000] + "\n\n_[Steps truncated]_"
        body_lines.extend([
            "### 📝 Player Bug Report",
            "",
            desc,
            "",
        ])
        if repro:
            body_lines.extend([
                "#### Steps to Reproduce",
                "",
                repro,
                "",
            ])

        eft_fit = (manual.get("ship_fitting_eft") or "").strip()
        if trim_sections and len(eft_fit) > 3_000:
            eft_fit = eft_fit[:3_000] + "\n# [truncated]"
        if eft_fit:
            body_lines.extend([
                "<details>",
                "<summary><b>🚀 Active Ship EFT Fitting (from igbr.zip)</b></summary>",
                "",
                "```text",
                eft_fit,
                "```",
                "",
                "</details>",
                "",
            ])

        client_logs = list(manual.get("client_logs_tail") or [])
        if trim_sections and len(client_logs) > 60:
            client_logs = [f"... [{len(client_logs) - 60} earlier client log lines omitted] ..."] + client_logs[-60:]
        if client_logs:
            body_lines.extend([
                "<details>",
                f"<summary><b>🖥️ Client Log Tail ({len(client_logs)} lines from igbr.zip)</b></summary>",
                "",
                "```log",
                "\n".join(str(ln) for ln in client_logs),
                "```",
                "",
                "</details>",
                "",
            ])

        attachments = manual.get("attachments") or []
        if attachments:
            body_lines.append("#### 📎 Staged Local Attachments")
            body_lines.append("")
            for rel_att in attachments:
                body_lines.append(f"- `{rel_att}`")
            body_lines.append("")

        comp_info = (manual.get("computer_info") or "").strip()
        if trim_sections and len(comp_info) > 4_000:
            comp_info = comp_info[:4_000] + "\n... [truncated]"
        if comp_info:
            body_lines.extend([
                "<details>",
                "<summary><b>💻 Client Hardware & Runtime Info</b></summary>",
                "",
                "```text",
                comp_info,
                "```",
                "",
                "</details>",
                "",
            ])

    if trace or not manual:
        body_lines.extend([
            "### 🐍 Client Python Traceback",
            "```python",
            trace if trace else "# [No client traceback provided]",
            "```",
            "",
        ])

    if flight_recorder:
        label_suffix = "before report" if manual else "before crash"
        body_lines.extend([
            "<details>",
            f"<summary><b>⏱️ MachoNet RPC Flight Recorder ({len(flight_recorder)} recent calls {label_suffix})</b></summary>",
            "",
            "| Time Offset | Service | Method | Args Summary | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            args = str(call.get("args_summary", "()")).replace("|", "\\|")
            if trim_sections and len(args) > 120:
                args = args[:117] + "..."
            status = str(call.get("status", "-")).replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            body_lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{args}` | `{status}` | `{dur_str}` |")
        body_lines.extend(["", "</details>", ""])

    all_logs = []
    if logs_before:
        all_logs.append("# --- Server logs prior to report ---")
        all_logs.extend(str(ln) for ln in logs_before)
    if logs_after:
        all_logs.append("# --- Trailing server logs (+1.5s window) ---")
        all_logs.extend(str(ln) for ln in logs_after)

    if all_logs:
        body_lines.extend([
            "<details>",
            f"<summary><b>📜 Server Log Slice ({len(all_logs)} lines)</b></summary>",
            "",
            "```log",
            "\n".join(all_logs),
            "```",
            "",
            "</details>",
            "",
        ])

    raw_payload = _compact_bundle_for_raw_json(bundle) if compact_raw_json else bundle
    body_lines.extend([
        "<details>",
        "<summary><b>🔍 Raw Session & Diagnostics Metadata</b></summary>",
        "",
        "```json",
        json.dumps(raw_payload, indent=2),
        "```",
        "",
        "</details>",
        "",
        "---",
        "*Automated report generated by EvoMu In-Band Telemetry & `sync_bugs_to_github.py`.*",
    ])

    return "\n".join(body_lines)


def format_markdown_issue(bundle: Dict[str, Any], occurrences: int = 1) -> str:
    """Formats an incident bundle into GitHub Markdown bounded below GitHub's 65,536-char limit."""
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=False, trim_sections=False)
    if len(body) <= MAX_GITHUB_BODY_CHARS:
        return body
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=True, trim_sections=False)
    if len(body) <= MAX_GITHUB_BODY_CHARS:
        return body
    body = _render_markdown_issue(bundle, occurrences, compact_raw_json=True, trim_sections=True)
    return _cap_markdown_body(body, MAX_GITHUB_BODY_CHARS)


def format_occurrence_comment(bundle: Dict[str, Any], total_occurrences: int) -> str:
    """Formats an additional occurrence comment for an existing issue."""
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    flight_recorder = bundle.get("flight_recorder", [])
    manual = bundle.get("manual_report") if is_manual_report(bundle) else None
    trace = _get_bundle_trace(bundle).strip()
    stack_key = str(bundle.get("stack_key") or "")
    req_counts = _extract_session_request_counts(bundle)
    build_info = _extract_build_info(bundle)

    lines = [
        f"### 🔁 New Incident Occurrence (#{total_occurrences})",
        f"- **Timestamp:** `{timestamp}`",
        f"- **Pilot:** `{char_name}` in `{system_name}`",
        f"- **Ship:** `{session.get('ship_type_name', 'Unknown')}`",
        (
            f"- **Session Telemetry:** server_requests=`{req_counts['server_requests']}`, "
            f"gateway_requests=`{req_counts['gateway_requests']}`"
        ),
    ]
    if build_info["client_build"] is not None or build_info["server_build"] is not None:
        lines.append(
            f"- **Handshake Build:** client=`{build_info['client_build'] or 'unknown'}`, "
            f"server=`{build_info['server_build'] or 'unknown'}`"
        )
    if trace:
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        headline = f"{exc_class}: {msg[:100]}" if msg else f"{exc_class} in {location}"
        lines.append(f"- **Exception / Location:** `{headline}` (`{location}`)")
    elif stack_key:
        lines.append(f"- **Stack Key:** `{stack_key}`")

    if manual:
        if manual.get("report_key"):
            lines.append(f"- **Report Key:** `{manual['report_key']}`")
        if manual.get("description"):
            lines.extend(["", manual["description"].strip()])

    if trace:
        capped_trace = trace if len(trace) <= 12_000 else trace[:12_000] + "\n# ... [traceback truncated] ..."
        lines.extend([
            "",
            "```python",
            capped_trace,
            "```",
        ])

    if flight_recorder:
        lines.extend([
            "",
            "<details>",
            f"<summary><b>⏱️ RPC Flight Recorder ({len(flight_recorder)} calls)</b></summary>",
            "",
            "| Time Offset | Service | Method | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder[-10:]:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            status = call.get("status", "-").replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{status}` | `{dur_str}` |")
        lines.extend(["", "</details>"])

    return _cap_markdown_body("\n".join(lines), MAX_GITHUB_BODY_CHARS)


def _run_gh_with_body_file(base_cmd: List[str], body: str) -> subprocess.CompletedProcess[str]:
    """Passes Markdown body via a closed UTF-8 temp file (`--body-file`) to avoid Windows
    `CreateProcessW` 32,767-char command-line limits (`WinError 206`) and console codepage issues.
    """
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", suffix=".md", delete=False) as tf:
        tf.write(body)
        body_path = tf.name
    try:
        return subprocess.run(
            base_cmd + ["--body-file", body_path],
            check=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    finally:
        try:
            os.remove(body_path)
        except OSError:
            pass


def check_gh_installed() -> bool:
    """Checks if GitHub CLI (`gh`) is available."""
    return shutil.which("gh") is not None


def ensure_github_labels(repo: str, labels: List[str], ensured_cache: Set[str]) -> None:
    """Best-effort ensures custom labels exist in the target GitHub repository."""
    if not check_gh_installed():
        return
    for label in labels:
        if label in ensured_cache:
            continue
        color, desc = LABEL_SPECS.get(label, ("ededed", "EvoMu bug report label"))
        cmd = [
            "gh", "label", "create", label,
            "--repo", repo,
            "--color", color,
            "--description", desc,
            "--force",
        ]
        try:
            subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
        except Exception:
            pass
        ensured_cache.add(label)


def find_existing_issue(repo: str, stack_hash: int, dry_run: bool = False) -> Optional[Tuple[int, str]]:
    """Queries GitHub CLI to check if an issue for this stack_hash already exists."""
    if dry_run or not check_gh_installed():
        return None

    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    search_terms = [
        f'"**Signature Hash:** `0x{unsigned_hash:016x}`" in:body',
        f'"(or `{stack_hash}`)" in:body',
    ]
    for term in search_terms:
        cmd = [
            "gh", "issue", "list",
            "--repo", repo,
            "--state", "all",
            "--search", term,
            "--json", "number,title,state",
            "--limit", "1",
        ]
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=True)
            issues = json.loads(res.stdout.strip() or "[]")
            if issues:
                return int(issues[0]["number"]), str(issues[0].get("state", "OPEN")).upper()
        except Exception as e:
            print(f"[warn] Failed to query gh for {term}: {e}", file=sys.stderr)
    return None


def _effective_bundle_hash(bundle: Dict[str, Any]) -> int:
    stack_hash = int(bundle.get("stack_hash", 0))
    stack_key = str(bundle.get("stack_key", ""))
    trace = _get_bundle_trace(bundle)

    env_fault = classify_environment_fault(bundle)
    if env_fault is not None:
        _, fingerprint, _ = env_fault
        h = _fnv1a_i64(fingerprint)
        bundle["stack_hash"] = h
        return h

    if _is_client_python_exception_bundle(bundle):
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        if exc_class != "UnknownException":
            norm_msg = _normalize_exception_message(msg)
            h = _fnv1a_i64(f"client-python-exc:{exc_class}:{location}:{norm_msg}")
            bundle["stack_hash"] = h
            return h

    if stack_hash == -1040548311 or "MollycoddledUthread" in stack_key:
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        base_hash = -1040548311 if "MollycoddledUthread" in stack_key else stack_hash
        h = _fnv1a_i64(f"{base_hash}:{location}:{exc_class}:{msg}")
        bundle["stack_hash"] = h
        return h
    return stack_hash


def _post_issue_comment(
    repo: str,
    issue_number: int,
    existing_state: str,
    comment_body: str,
    dry_run: bool = False,
) -> bool:
    """Posts an occurrence comment to an existing issue (reopening if closed)."""
    if dry_run:
        if existing_state == "CLOSED":
            print(f"[dry-run] Would reopen closed issue #{issue_number}")
        preview = comment_body if len(comment_body) <= 2000 else comment_body[:2000] + "..."
        print(f"[dry-run] Would post comment to #{issue_number}:\n{preview}\n")
        return True

    if existing_state == "CLOSED":
        try:
            subprocess.run(
                ["gh", "issue", "reopen", str(issue_number), "--repo", repo],
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=True,
            )
            print(f"[+] Reopened closed issue #{issue_number} due to new occurrence")
        except subprocess.CalledProcessError as e:
            print(f"[warn] Failed to reopen issue #{issue_number}: {e.stderr}", file=sys.stderr)

    cmd = [
        "gh", "issue", "comment",
        str(issue_number),
        "--repo", repo,
    ]
    try:
        _run_gh_with_body_file(cmd, comment_body)
        print(f"[+] Added incident occurrence comment to issue #{issue_number}")
        return True
    except subprocess.CalledProcessError as e:
        print(f"[error] Failed to comment on issue #{issue_number}: {e.stderr}", file=sys.stderr)
        return False


def create_or_update_issue(
    repo: str,
    bundle: Dict[str, Any],
    occurrences: int = 1,
    ensured_labels: Optional[Set[str]] = None,
    dry_run: bool = False,
) -> Optional[int]:
    """Creates a new issue or comments on an existing one (reopening if closed)."""
    if ensured_labels is None:
        ensured_labels = set()
    stack_hash = _effective_bundle_hash(bundle)
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    title, labels = build_issue_title_and_labels(bundle)

    existing = find_existing_issue(repo, stack_hash, dry_run=dry_run)

    if existing:
        existing_number, existing_state = existing
        print(f"[*] Found existing issue #{existing_number} (state={existing_state}) for hash 0x{unsigned_hash:016x}")
        comment_body = format_occurrence_comment(bundle, occurrences)
        if _post_issue_comment(repo, existing_number, existing_state, comment_body, dry_run=dry_run):
            return existing_number
        return None
    else:
        issue_body = format_markdown_issue(bundle, occurrences)
        if dry_run:
            print(f"[dry-run] Would create issue with title: {title} (labels: {','.join(labels)})")
            print(f"[dry-run] Body preview:\n{issue_body[:500]}...\n")
            return 999999

        ensure_github_labels(repo, labels, ensured_labels)
        cmd = [
            "gh", "issue", "create",
            "--repo", repo,
            "--title", title,
            "--label", ",".join(labels),
        ]
        try:
            res = _run_gh_with_body_file(cmd, issue_body)
        except subprocess.CalledProcessError:
            # Fallback without custom labels if the user lacks label-creation permission
            fallback_cmd = [
                "gh", "issue", "create",
                "--repo", repo,
                "--title", title,
            ]
            try:
                res = _run_gh_with_body_file(fallback_cmd, issue_body)
            except subprocess.CalledProcessError as e:
                print(f"[error] Failed to create issue: {e.stderr}", file=sys.stderr)
                return None

        output = res.stdout.strip()
        print(f"[+] Created issue: {output}")
        m = re.search(r"/issues/(\d+)", output)
        return int(m.group(1)) if m else 1


def is_safe_report_key(key: str) -> bool:
    return bool(key) and len(key) <= 64 and all(c.isalnum() or c in "-_" for c in key)


def archive_or_delete_attachments(
    queue_dir: str,
    uploaded_dir: str,
    bundle: Dict[str, Any],
    delete: bool,
) -> None:
    manual = bundle.get("manual_report")
    if not isinstance(manual, dict):
        return
    report_key = str(manual.get("report_key") or "").strip()
    if not is_safe_report_key(report_key):
        return

    src_dir = os.path.join(queue_dir, "attachments", report_key)
    if not os.path.isdir(src_dir):
        return

    if delete:
        shutil.rmtree(src_dir, ignore_errors=True)
    else:
        dest_parent = os.path.join(uploaded_dir, "attachments")
        os.makedirs(dest_parent, exist_ok=True)
        dest_dir = os.path.join(dest_parent, report_key)
        if os.path.exists(dest_dir):
            shutil.rmtree(dest_dir, ignore_errors=True)
        try:
            shutil.move(src_dir, dest_dir)
        except OSError as e:
            print(f"[warn] Could not archive attachments '{src_dir}' to '{dest_dir}': {e}", file=sys.stderr)


def _select_primary_and_extras(
    files: List[Tuple[str, Dict[str, Any]]],
) -> Tuple[Tuple[str, Dict[str, Any]], List[Tuple[str, Dict[str, Any]]]]:
    """Prefer auto-reported `[Client Crash]` over `[Bug Report][client-python]` as primary."""
    primary_idx = 0
    for idx, (_, b) in enumerate(files):
        if not is_manual_report(b):
            primary_idx = idx
            break
    primary = files[primary_idx]
    extras = [item for idx, item in enumerate(files) if idx != primary_idx]
    return primary, extras


def _should_comment_extra_bundle(
    primary_bundle: Dict[str, Any],
    extra_bundle: Dict[str, Any],
    env_fault: Optional[Tuple[str, str, str]],
) -> bool:
    if env_fault is not None:
        return True
    if is_manual_report(extra_bundle) != is_manual_report(primary_bundle):
        return True
    if _get_bundle_trace(extra_bundle).strip() != _get_bundle_trace(primary_bundle).strip():
        return True
    return False


def main(argv: Optional[List[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")

    parser = argparse.ArgumentParser(description="Sync EvoMu client bug reports from local queue to GitHub issues.")
    parser.add_argument("--queue-dir", default=".evomu-bugs/queue", help="Path to bug reports queue directory")
    parser.add_argument("--uploaded-dir", default=".evomu-bugs/uploaded", help="Path to archive uploaded bug reports")
    parser.add_argument("--repo", default="saverchenkov/EvoMu", help="GitHub repository (owner/name)")
    parser.add_argument("--dry-run", action="store_true", help="Print actions without modifying GitHub or files")
    parser.add_argument("--delete", action="store_true", help="Delete report files and attachments instead of archiving")
    parser.add_argument("--verbose", action="store_true", help="Enable verbose logging")

    args = parser.parse_args(argv)

    if not os.path.exists(args.queue_dir):
        print(f"[*] Queue directory '{args.queue_dir}' does not exist or is empty. No bugs to report.")
        return 0

    json_files = sorted(glob.glob(os.path.join(args.queue_dir, "*.json")))
    if not json_files:
        print(f"[*] No pending bug reports in '{args.queue_dir}'.")
        return 0

    print(f"[*] Discovered {len(json_files)} queued incident report(s) in '{args.queue_dir}'.")

    groups: Dict[int, List[Tuple[str, Dict[str, Any]]]] = {}
    for filepath in json_files:
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                bundle = json.load(f)
            h = _effective_bundle_hash(bundle)
            groups.setdefault(h, []).append((filepath, bundle))
        except Exception as e:
            print(f"[warn] Skipping corrupt or unreadable file '{filepath}': {e}", file=sys.stderr)

    if not args.dry_run and not args.delete:
        os.makedirs(args.uploaded_dir, exist_ok=True)

    ensured_labels: Set[str] = set()
    success_count = 0
    for stack_hash, files in groups.items():
        total_occurrences = len(files)
        unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
        (_, primary_bundle), extra_files = _select_primary_and_extras(files)
        env_fault = classify_environment_fault(primary_bundle)
        print(f"[*] Processing error group 0x{unsigned_hash:016x} ({total_occurrences} occurrence(s))...")

        issue_id = create_or_update_issue(
            args.repo,
            primary_bundle,
            total_occurrences,
            ensured_labels=ensured_labels,
            dry_run=args.dry_run,
        )
        if issue_id:
            for occ_idx, (_, extra_bundle) in enumerate(extra_files, start=2):
                if _should_comment_extra_bundle(primary_bundle, extra_bundle, env_fault):
                    comment_body = format_occurrence_comment(extra_bundle, occ_idx)
                    _post_issue_comment(
                        args.repo,
                        issue_id,
                        "OPEN",
                        comment_body,
                        dry_run=args.dry_run,
                    )

        if issue_id or args.dry_run:
            success_count += len(files)
            for path, file_bundle in files:
                if args.dry_run:
                    continue
                if args.delete:
                    try:
                        os.remove(path)
                    except OSError:
                        pass
                else:
                    dest = os.path.join(args.uploaded_dir, os.path.basename(path))
                    try:
                        shutil.move(path, dest)
                    except OSError as e:
                        print(f"[warn] Could not archive '{path}' to '{dest}': {e}", file=sys.stderr)
                archive_or_delete_attachments(
                    args.queue_dir,
                    args.uploaded_dir,
                    file_bundle,
                    delete=args.delete,
                )

    print(f"[✓] Processed {success_count}/{len(json_files)} incident file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
