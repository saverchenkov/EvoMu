#!/usr/bin/env python3
"""
EvoMu Client Bug Reporting & GitHub Sync CLI

Scans `.evomu-bugs/queue/` for structured incident bundles generated by EvoMu's:
  1. Automatic in-band exception telemetry (`alert.SendClientStackTraceAlert`)
  2. Native V24 `F12 -> Report a Bug` (`bugreporter` `/bugs/api/*` endpoints)

Deduplicates reports by signature hash against GitHub issues on `saverchenkov/EvoMu`,
and creates or updates issues with full diagnostic context:
  - Client Python traceback or player-submitted description & reproduction steps
  - Extracted active ship EFT fitting (`fitting.txt`) & client log tail (`logs.txt`) from `igbr.zip`
  - MachoNet RPC Flight Recorder (causality table of preceding calls)
  - Server log slice (events before and trailing +1.5s window after)
  - Spatial & character snapshot (solar system, station/structure, coordinates, ship hull)

Usage:
    python3 tools/sync_bugs_to_github.py [--dry-run] [--delete] [--repo saverchenkov/EvoMu]
"""

import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Set, Tuple


LABEL_SPECS: Dict[str, Tuple[str, str]] = {
    "bug": ("d73a4a", "Something isn't working"),
    "client-crash": ("b60205", "Unhandled Python exception reported by EVE client"),
    "auto-reported": ("0e8a16", "Captured automatically via EvoMu in-band telemetry"),
    "player-reported": ("1d76db", "Submitted in-game via F12 Report a Bug"),
}


def parse_traceback_summary(trace: str, stack_key: str) -> Tuple[str, str, str]:
    """
    Extracts (exception_class, error_msg, location) from a Python stack trace.
    Returns e.g. ("TypeError", "'NoneType' object is not subscriptable", "map.pyj:412 in Open").
    """
    lines = [line.strip() for line in trace.strip().splitlines() if line.strip()]
    if not lines:
        return "UnknownException", "No traceback provided", stack_key or "unknown"

    last_line = lines[-1]
    if ":" in last_line:
        exc_class, msg = last_line.split(":", 1)
        exc_class = exc_class.strip()
        msg = msg.strip()
    else:
        exc_class = last_line.strip()
        msg = ""

    location = stack_key or "unknown"
    for line in reversed(lines[:-1]):
        m = re.search(r'File\s+["\']([^"\']+)["\'],\s+line\s+(\d+)(?:,\s+in\s+(\w+))?', line)
        if m:
            filepath = os.path.basename(m.group(1))
            lineno = m.group(2)
            fn = m.group(3)
            if fn:
                location = f"{filepath}:{lineno} in {fn}"
            else:
                location = f"{filepath}:{lineno}"
            break

    return exc_class, msg, location


def is_manual_report(bundle: Dict[str, Any]) -> bool:
    return bundle.get("report_source") == "f12_manual" or isinstance(bundle.get("manual_report"), dict)


def build_issue_title_and_labels(bundle: Dict[str, Any]) -> Tuple[str, List[str]]:
    if is_manual_report(bundle):
        manual = bundle.get("manual_report") or {}
        cat = (manual.get("category_id") or "Gameplay").strip()
        summary = (manual.get("title") or "Untitled Bug Report").strip()
        title = f"[Bug Report][{cat}] {summary}"
        labels = ["bug", "player-reported"]
    else:
        trace = bundle.get("trace", "")
        stack_key = bundle.get("stack_key", "")
        exc_class, msg, location = parse_traceback_summary(trace, stack_key)
        title = (
            f"[Client Crash] {exc_class}: {msg[:60]}"
            if msg
            else f"[Client Crash] {exc_class} in {location}"
        )
        labels = ["bug", "client-crash", "auto-reported"]

    if len(title) > 100:
        title = title[:97] + "..."
    return title, labels


def format_markdown_issue(bundle: Dict[str, Any], occurrences: int = 1) -> str:
    """Formats an incident bundle (automatic crash or F12 manual bug report) into GitHub Markdown."""
    trace = bundle.get("trace", "").strip()
    stack_key = bundle.get("stack_key", "")
    stack_hash = bundle.get("stack_hash", 0)
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    sec_status = session.get("security_status")
    sec_str = f" ({sec_status:+.1f})" if isinstance(sec_status, (int, float)) else ""
    ship_name = session.get("ship_type_name") or f"Ship #{session.get('ship_type_id', 'unknown')}"

    station_id = session.get("station_id")
    structure_id = session.get("structure_id")
    coords = session.get("coordinates")
    if station_id:
        location_desc = f"Docked at NPC Station #{station_id}"
    elif structure_id:
        location_desc = f"Docked at Upwell Structure #{structure_id}"
    elif coords:
        location_desc = (
            f"In space at `({coords.get('x', 0):.0f}, {coords.get('y', 0):.0f}, {coords.get('z', 0):.0f})`"
        )
    else:
        location_desc = "Unknown location"

    flight_recorder = bundle.get("flight_recorder", [])
    logs_before = bundle.get("server_logs_before", [])
    logs_after = bundle.get("server_logs_after", [])
    manual = bundle.get("manual_report") if is_manual_report(bundle) else None

    body_lines = [
        f"**Signature Hash:** `0x{unsigned_hash:016x}` (or `{stack_hash}`) | **Occurrences Captured:** `{occurrences}`",
        f"**Reported At:** `{timestamp}` | **Stack Key:** `{stack_key}`",
    ]
    if manual:
        report_key = manual.get("report_key") or "unknown"
        cat_name = manual.get("category_name") or manual.get("category_id") or "Gameplay"
        cat_id = manual.get("category_id") or "Gameplay"
        build_num = manual.get("client_build")
        build_str = f" | **Client Build:** `{build_num}`" if build_num is not None else ""
        body_lines.append(
            f"**Report Key:** `{report_key}` | **Category:** `{cat_name}` (`{cat_id}`){build_str}"
        )

    body_lines.extend([
        f"**Pilot:** `{char_name}` (ID: `{session.get('character_id')}`) | **System:** `{system_name}`{sec_str}",
        f"**Location:** {location_desc} | **Ship Hull:** `{ship_name}`",
        "",
        "---",
        "",
    ])

    if manual:
        desc = (manual.get("description") or "").strip() or "_No description provided._"
        repro = (manual.get("reproduction_steps") or "").strip()
        body_lines.extend([
            "### 📝 Player Bug Report",
            "",
            desc,
            "",
        ])
        if repro:
            body_lines.extend([
                "#### Steps to Reproduce",
                "",
                repro,
                "",
            ])

        eft_fit = (manual.get("ship_fitting_eft") or "").strip()
        if eft_fit:
            body_lines.extend([
                "<details>",
                "<summary><b>🚀 Active Ship EFT Fitting (from igbr.zip)</b></summary>",
                "",
                "```text",
                eft_fit,
                "```",
                "",
                "</details>",
                "",
            ])

        client_logs = manual.get("client_logs_tail") or []
        if client_logs:
            body_lines.extend([
                "<details>",
                f"<summary><b>🖥️ Client Log Tail ({len(client_logs)} lines from igbr.zip)</b></summary>",
                "",
                "```log",
                "\n".join(client_logs),
                "```",
                "",
                "</details>",
                "",
            ])

        attachments = manual.get("attachments") or []
        if attachments:
            body_lines.append("#### 📎 Staged Local Attachments")
            body_lines.append("")
            for rel_att in attachments:
                body_lines.append(f"- `{rel_att}`")
            body_lines.append("")

        comp_info = (manual.get("computer_info") or "").strip()
        if comp_info:
            body_lines.extend([
                "<details>",
                "<summary><b>💻 Client Hardware & Runtime Info</b></summary>",
                "",
                "```text",
                comp_info,
                "```",
                "",
                "</details>",
                "",
            ])

    if trace or not manual:
        body_lines.extend([
            "### 🐍 Client Python Traceback",
            "```python",
            trace if trace else "# [No client traceback provided]",
            "```",
            "",
        ])

    if flight_recorder:
        label_suffix = "before report" if manual else "before crash"
        body_lines.extend([
            "<details>",
            f"<summary><b>⏱️ MachoNet RPC Flight Recorder ({len(flight_recorder)} recent calls {label_suffix})</b></summary>",
            "",
            "| Time Offset | Service | Method | Args Summary | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            args = call.get("args_summary", "()").replace("|", "\\|")
            status = call.get("status", "-").replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            body_lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{args}` | `{status}` | `{dur_str}` |")
        body_lines.extend(["", "</details>", ""])

    all_logs = []
    if logs_before:
        all_logs.append("# --- Server logs prior to report ---")
        all_logs.extend(logs_before)
    if logs_after:
        all_logs.append("# --- Trailing server logs (+1.5s window) ---")
        all_logs.extend(logs_after)

    if all_logs:
        body_lines.extend([
            "<details>",
            f"<summary><b>📜 Server Log Slice ({len(all_logs)} lines)</b></summary>",
            "",
            "```log",
            "\n".join(all_logs),
            "```",
            "",
            "</details>",
            "",
        ])

    body_lines.extend([
        "<details>",
        "<summary><b>🔍 Raw Session & Diagnostics Metadata</b></summary>",
        "",
        "```json",
        json.dumps(bundle, indent=2),
        "```",
        "",
        "</details>",
        "",
        "---",
        "*Automated report generated by EvoMu In-Band Telemetry & `sync_bugs_to_github.py`.*",
    ])

    return "\n".join(body_lines)


def format_occurrence_comment(bundle: Dict[str, Any], total_occurrences: int) -> str:
    """Formats an additional occurrence comment for an existing issue."""
    timestamp = bundle.get("timestamp", datetime.now(timezone.utc).isoformat())
    session = bundle.get("session", {})
    char_name = session.get("character_name") or f"Char #{session.get('character_id', 'unknown')}"
    system_name = session.get("solar_system_name") or f"System #{session.get('solar_system_id', 'unknown')}"
    flight_recorder = bundle.get("flight_recorder", [])
    manual = bundle.get("manual_report") if is_manual_report(bundle) else None

    lines = [
        f"### 🔁 New Incident Occurrence (#{total_occurrences})",
        f"- **Timestamp:** `{timestamp}`",
        f"- **Pilot:** `{char_name}` in `{system_name}`",
        f"- **Ship:** `{session.get('ship_type_name', 'Unknown')}`",
    ]
    if manual:
        if manual.get("report_key"):
            lines.append(f"- **Report Key:** `{manual['report_key']}`")
        if manual.get("description"):
            lines.extend(["", manual["description"].strip()])

    if flight_recorder:
        lines.extend([
            "",
            "<details>",
            f"<summary><b>⏱️ RPC Flight Recorder ({len(flight_recorder)} calls)</b></summary>",
            "",
            "| Time Offset | Service | Method | Status | Duration |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for call in flight_recorder[-10:]:
            offset_str = f"{call.get('offset_ms', 0):+d}ms" if "offset_ms" in call else "-"
            svc = call.get("service", "-")
            method = call.get("method", "-")
            status = call.get("status", "-").replace("|", "\\|")
            duration_us = call.get("duration_micros", 0)
            dur_str = f"{duration_us / 1000.0:.2f}ms" if duration_us else "-"
            lines.append(f"| `{offset_str}` | `{svc}` | `{method}` | `{status}` | `{dur_str}` |")
        lines.extend(["", "</details>"])

    return "\n".join(lines)


def check_gh_installed() -> bool:
    """Checks if GitHub CLI (`gh`) is available."""
    return shutil.which("gh") is not None


def ensure_github_labels(repo: str, labels: List[str], ensured_cache: Set[str]) -> None:
    """Best-effort ensures custom labels exist in the target GitHub repository."""
    if not check_gh_installed():
        return
    for label in labels:
        if label in ensured_cache:
            continue
        color, desc = LABEL_SPECS.get(label, ("ededed", "EvoMu bug report label"))
        cmd = [
            "gh", "label", "create", label,
            "--repo", repo,
            "--color", color,
            "--description", desc,
            "--force",
        ]
        try:
            subprocess.run(cmd, capture_output=True, text=True, check=False)
        except Exception:
            pass
        ensured_cache.add(label)


def find_existing_issue(repo: str, stack_hash: int, dry_run: bool = False) -> Optional[int]:
    """Queries GitHub CLI to check if an issue for this stack_hash already exists."""
    if dry_run or not check_gh_installed():
        return None

    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    search_terms = [f"0x{unsigned_hash:016x}", str(stack_hash)]
    for term in search_terms:
        cmd = [
            "gh", "issue", "list",
            "--repo", repo,
            "--state", "all",
            "--search", term,
            "--json", "number,title,state",
            "--limit", "1",
        ]
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, check=True)
            issues = json.loads(res.stdout.strip() or "[]")
            if issues:
                return issues[0]["number"]
        except Exception as e:
            print(f"[warn] Failed to query gh for {term}: {e}", file=sys.stderr)
    return None


def create_or_update_issue(
    repo: str,
    bundle: Dict[str, Any],
    occurrences: int,
    ensured_labels: Set[str],
    dry_run: bool = False,
) -> Optional[int]:
    """Creates a new issue or comments on an existing one."""
    stack_hash = bundle.get("stack_hash", 0)
    unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
    title, labels = build_issue_title_and_labels(bundle)

    existing_number = find_existing_issue(repo, stack_hash, dry_run=dry_run)

    if existing_number:
        print(f"[*] Found existing issue #{existing_number} for hash 0x{unsigned_hash:016x}")
        comment_body = format_occurrence_comment(bundle, occurrences)
        if dry_run:
            print(f"[dry-run] Would post comment to #{existing_number}:\n{comment_body[:300]}...\n")
            return existing_number

        cmd = [
            "gh", "issue", "comment",
            str(existing_number),
            "--repo", repo,
            "--body", comment_body,
        ]
        try:
            subprocess.run(cmd, check=True, capture_output=True, text=True)
            print(f"[+] Added incident occurrence comment to issue #{existing_number}")
            return existing_number
        except subprocess.CalledProcessError as e:
            print(f"[error] Failed to comment on issue #{existing_number}: {e.stderr}", file=sys.stderr)
            return None
    else:
        issue_body = format_markdown_issue(bundle, occurrences)
        if dry_run:
            print(f"[dry-run] Would create issue with title: {title} (labels: {','.join(labels)})")
            print(f"[dry-run] Body preview:\n{issue_body[:500]}...\n")
            return 999999

        ensure_github_labels(repo, labels, ensured_labels)
        cmd = [
            "gh", "issue", "create",
            "--repo", repo,
            "--title", title,
            "--body", issue_body,
            "--label", ",".join(labels),
        ]
        try:
            res = subprocess.run(cmd, check=True, capture_output=True, text=True)
        except subprocess.CalledProcessError:
            # Fallback without custom labels if the user lacks label-creation permission
            fallback_cmd = [
                "gh", "issue", "create",
                "--repo", repo,
                "--title", title,
                "--body", issue_body,
            ]
            try:
                res = subprocess.run(fallback_cmd, check=True, capture_output=True, text=True)
            except subprocess.CalledProcessError as e:
                print(f"[error] Failed to create issue: {e.stderr}", file=sys.stderr)
                return None

        output = res.stdout.strip()
        print(f"[+] Created issue: {output}")
        m = re.search(r"/issues/(\d+)", output)
        return int(m.group(1)) if m else 1


def is_safe_report_key(key: str) -> bool:
    return bool(key) and len(key) <= 64 and all(c.isalnum() or c in "-_" for c in key)


def archive_or_delete_attachments(
    queue_dir: str,
    uploaded_dir: str,
    bundle: Dict[str, Any],
    delete: bool,
) -> None:
    manual = bundle.get("manual_report")
    if not isinstance(manual, dict):
        return
    report_key = str(manual.get("report_key") or "").strip()
    if not is_safe_report_key(report_key):
        return

    src_dir = os.path.join(queue_dir, "attachments", report_key)
    if not os.path.isdir(src_dir):
        return

    if delete:
        shutil.rmtree(src_dir, ignore_errors=True)
    else:
        dest_parent = os.path.join(uploaded_dir, "attachments")
        os.makedirs(dest_parent, exist_ok=True)
        dest_dir = os.path.join(dest_parent, report_key)
        if os.path.exists(dest_dir):
            shutil.rmtree(dest_dir, ignore_errors=True)
        try:
            shutil.move(src_dir, dest_dir)
        except OSError as e:
            print(f"[warn] Could not archive attachments '{src_dir}' to '{dest_dir}': {e}", file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync EvoMu client bug reports from local queue to GitHub issues.")
    parser.add_argument("--queue-dir", default=".evomu-bugs/queue", help="Path to bug reports queue directory")
    parser.add_argument("--uploaded-dir", default=".evomu-bugs/uploaded", help="Path to archive uploaded bug reports")
    parser.add_argument("--repo", default="saverchenkov/EvoMu", help="GitHub repository (owner/name)")
    parser.add_argument("--dry-run", action="store_true", help="Print actions without modifying GitHub or files")
    parser.add_argument("--delete", action="store_true", help="Delete report files and attachments instead of archiving")
    parser.add_argument("--verbose", action="store_true", help="Enable verbose logging")

    args = parser.parse_args()

    if not os.path.exists(args.queue_dir):
        print(f"[*] Queue directory '{args.queue_dir}' does not exist or is empty. No bugs to report.")
        return 0

    json_files = sorted(glob.glob(os.path.join(args.queue_dir, "*.json")))
    if not json_files:
        print(f"[*] No pending bug reports in '{args.queue_dir}'.")
        return 0

    print(f"[*] Discovered {len(json_files)} queued incident report(s) in '{args.queue_dir}'.")

    groups: Dict[int, List[Tuple[str, Dict[str, Any]]]] = {}
    for filepath in json_files:
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                bundle = json.load(f)
            h = bundle.get("stack_hash", 0)
            groups.setdefault(h, []).append((filepath, bundle))
        except Exception as e:
            print(f"[warn] Skipping corrupt or unreadable file '{filepath}': {e}", file=sys.stderr)

    if not args.dry_run and not args.delete:
        os.makedirs(args.uploaded_dir, exist_ok=True)

    ensured_labels: Set[str] = set()
    success_count = 0
    for stack_hash, files in groups.items():
        total_occurrences = len(files)
        unsigned_hash = stack_hash & 0xFFFFFFFFFFFFFFFF
        _, latest_bundle = files[-1]
        print(f"[*] Processing error group 0x{unsigned_hash:016x} ({total_occurrences} occurrence(s))...")

        issue_id = create_or_update_issue(
            args.repo,
            latest_bundle,
            total_occurrences,
            ensured_labels=ensured_labels,
            dry_run=args.dry_run,
        )
        if issue_id or args.dry_run:
            success_count += len(files)
            for path, file_bundle in files:
                if args.dry_run:
                    continue
                if args.delete:
                    try:
                        os.remove(path)
                    except OSError:
                        pass
                else:
                    dest = os.path.join(args.uploaded_dir, os.path.basename(path))
                    try:
                        shutil.move(path, dest)
                    except OSError as e:
                        print(f"[warn] Could not archive '{path}' to '{dest}': {e}", file=sys.stderr)
                archive_or_delete_attachments(
                    args.queue_dir,
                    args.uploaded_dir,
                    file_bundle,
                    delete=args.delete,
                )

    print(f"[✓] Processed {success_count}/{len(json_files)} incident file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
