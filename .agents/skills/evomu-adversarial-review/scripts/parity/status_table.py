#!/usr/bin/python3
"""Generate docs/ACTION_PLAN_STATUS.md mechanically from parity results. Never hand-edit the output.

Why: the hand-written tracker with file:line evidence went stale on every refactor and caused review
rounds R41-R46 without adding features. The tracker is now a pure function of:
  - the pinned plan (task ids, titles, phases),
  - parity.json (plan:<id> row status, feat rows mapped to each task, tagged tests),
  - git log (last commit whose message mentions the task id),
  - docs/parity/task_notes.json (the agent's short assessment + note per task; optional).

task_notes.json format: {"S-1": {"assessment": "NOT STARTED|PARTIAL|DONE", "note": "<= 200 chars"}}
Rules enforced here: an assessment of DONE is shown as DONE only if the plan row is mechanically DONE;
notes containing file:line citations or digits-heavy claims are dropped (put evidence in tests, not prose).

Usage: status_table.py --parity <parity.json> [--out docs/ACTION_PLAN_STATUS.md]
"""
import argparse
import json
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(os.path.dirname(HERE))
PLAN = os.path.join(SKILL, "references", "action_plan.md")
LEDGER = os.path.join(SKILL, "references", "parity", "ledger.json")
AUDITOR = os.path.join(SKILL, "references", "parity", "auditor_rows.json")
ID_RE = r"(?:S|D|P|SP|DG|C|MN|CH|E|SO|T|Q|ESI|Z)-\d+"
CITE_RE = re.compile(r"[A-Za-z0-9_./\-]+\.(?:rs|py|md|toml|json|sql|c|sh|txt):\d+")


def plan_structure():
    phases, cur, titles = [], None, {}
    for ln in open(PLAN, encoding="utf-8"):
        h = re.match(r"^## (Phase [^:]+):?\s*(.*)$", ln)
        if h:
            cur = [h.group(1).strip() + (": " + h.group(2).strip() if h.group(2) else ""), []]
            phases.append(cur)
            continue
        if ln.startswith("## "):
            cur = None
            continue
        m = re.match(r"^\|\s*\**`?(" + ID_RE + r")`?\**\s*\|\s*([^|]*)\|", ln)
        if m and cur is not None:
            tid = m.group(1)
            if tid not in cur[1]:
                cur[1].append(tid)
            t = re.sub(r"[*`]", "", m.group(2)).strip()
            t = re.sub(r"\s*\([^()]*\.(?:rs|py|md|json|sql|cpp|h)(?::[\d,\- ]+)?[^()]*\)", "", t).strip()
            titles.setdefault(tid, (t[:80] + "…") if len(t) > 80 else t)
    return [p for p in phases if p[1]], titles


def last_commit(root, tid):
    out = subprocess.run(["git", "log", "-1", "-E", "--format=%h %ad", "--date=short",
                          "--grep", r"(^|[^A-Za-z0-9-])%s([^0-9]|$)" % re.escape(tid)],
                         cwd=root, capture_output=True, text=True).stdout.strip()
    return out or "—"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--parity", required=True)
    ap.add_argument("--out")
    a = ap.parse_args()
    root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                          cwd=os.getcwd()).stdout.strip()
    out_path = a.out or os.path.join(root, "docs", "ACTION_PLAN_STATUS.md")
    par = json.load(open(a.parity))
    prow, summ = par["rows"], par["summary"]
    ledger = {r["id"]: r for r in json.load(open(LEDGER))["rows"]}
    fake = set()
    if os.path.exists(AUDITOR):
        aud = json.load(open(AUDITOR))
        for r in aud.get("rows", []):
            ledger.setdefault(r["id"], r)
        fake = {f["id"] for f in aud.get("fake_done", [])}
    feats_by_task = {}
    for r in ledger.values():
        if r.get("category") == "feat" and r.get("plan_task"):
            feats_by_task.setdefault(r["plan_task"], []).append(r["id"])
    notes_path = os.path.join(root, "docs", "parity", "task_notes.json")
    notes = json.load(open(notes_path)) if os.path.exists(notes_path) else {}
    phases, titles = plan_structure()

    L = ["<!-- GENERATED by .agents/skills/evomu-adversarial-review/scripts/parity/status_table.py "
         "(run via preflight.py). DO NOT EDIT BY HAND: edit docs/parity/task_notes.json instead. -->", "",
         "# EvoMu action plan status (generated)", "",
         "The canonical plan is `.agents/skills/evomu-adversarial-review/references/action_plan.md`. This file "
         "is regenerated from the latest pre-flight parity run, so it can't go stale or be overstated.", "",
         "**Parity: %d / %d ledger rows closed (%.2f%%)**, %d NA, %d tagged tests, %d passing tests. "
         "Flagged fake by the gap auditor: %d." % (summ["closed_rows"], summ["total_rows"], summ["percent_closed"],
                                                  summ["na_rows"], summ["tagged_tests"], summ["passed_tests"],
                                                  len(fake)), "",
         "| Category | Total | DONE | NA | Open |", "|---|---|---|---|---|"]
    for k, c in sorted(summ["categories"].items()):
        L.append("| %s | %d | %d | %d | %d |" % (k, c["total"], c["DONE"], c["NA"], c["open"]))
    L += ["", "Columns: **Ledger** = mechanical status of the `plan:<id>` row; **Features** = mapped `feat:` rows "
          "closed/total; **Assessment** = the agent's own judgement from `docs/parity/task_notes.json` (DONE is "
          "accepted only when the ledger row is DONE)."]
    for name, ids in phases:
        L += ["", "## " + name, "", "| Task | Title | Ledger | Features | Tests | Assessment | Note | Last commit |",
              "|---|---|---|---|---|---|---|---|"]
        for tid in ids:
            pr = prow.get("plan:" + tid, {})
            st = pr.get("status", "MISSING")
            if "plan:" + tid in fake:
                st = "FLAGGED_FAKE"
            fs = feats_by_task.get(tid, [])
            closed = sum(1 for f in fs if (prow.get(f) or {}).get("status") in ("DONE", "NA"))
            tests = ", ".join(pr.get("tests") or [])[:120] or "—"
            n = notes.get(tid) or {}
            assess = str(n.get("assessment", "")).upper() or "—"
            if assess == "DONE" and st != "DONE":
                assess = "PARTIAL (claimed DONE, ledger %s)" % st
            note = str(n.get("note", ""))[:200]
            if CITE_RE.search(note):
                note = "[note dropped: contains a file:line citation]"
            note = note.replace("|", "/").replace("\n", " ") or "—"
            L.append("| %s | %s | %s | %d/%d | %s | %s | %s | %s |" % (
                tid, titles.get(tid, "").replace("|", "/"), st, closed, len(fs), tests, assess, note,
                last_commit(root, tid)))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w").write("\n".join(L) + "\n")
    print("[status] wrote %s (%d phases)" % (out_path, len(phases)))


if __name__ == "__main__":
    main()
