#!/usr/bin/python3
"""Shared helpers for the EvoMu adversarial review skill.

- Working-tree fingerprint = git tree hash of the full working tree (tracked + untracked,
  respecting .gitignore), computed through a temporary index so the real index is untouched.
  After `git add -A && git commit`, HEAD^{tree} equals this fingerprint.
- Review state lives in <repo>/.evomu-reviews/ (gitignored, so it never changes the fingerprint).
"""
import json
import os
import re
import subprocess
import tempfile

STATE_DIRNAME = ".evomu-reviews"
# Written by the orchestrator after gap audits; excluded from the fingerprint so an audit does not
# itself invalidate the tree it just reviewed.
AUDITOR_ROWS_REL = ".agents/skills/evomu-adversarial-review/references/parity/auditor_rows.json"


def repo_root(start=None):
    start = start or os.path.dirname(os.path.abspath(__file__))
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start,
                         capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit("not inside a git repository: %s" % start)
    return out.stdout.strip()


def worktree_fingerprint(root):
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(d, "index"))
        if subprocess.run(["git", "rev-parse", "--verify", "-q", "HEAD"], cwd=root,
                          capture_output=True).returncode == 0:
            subprocess.run(["git", "read-tree", "HEAD"], cwd=root, env=env, check=True,
                           capture_output=True)
        subprocess.run(["git", "add", "-A", "--", ".", ":(exclude)%s" % STATE_DIRNAME, ":(exclude)%s" % AUDITOR_ROWS_REL], cwd=root,
                       env=env, check=True, capture_output=True)
        return subprocess.run(["git", "write-tree"], cwd=root, env=env, check=True,
                              capture_output=True, text=True).stdout.strip()


def head_tree(root):
    out = subprocess.run(["git", "rev-parse", "HEAD^{tree}"], cwd=root,
                         capture_output=True, text=True)
    return out.stdout.strip() if out.returncode == 0 else ""


def state_dir(root):
    p = os.environ.get("EVOMU_STATE_DIR") or os.path.join(root, STATE_DIRNAME)
    os.makedirs(p, exist_ok=True)
    return p


def load_state(root):
    p = os.path.join(state_dir(root), "state.json")
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return {"reviews": []}


def save_state(root, state):
    p = os.path.join(state_dir(root), "state.json")
    tmp = p + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2)
    os.replace(tmp, p)


def reviewed_trees(state, verdicts=None):
    return {r["tree"] for r in state.get("reviews", [])
            if verdicts is None or r.get("verdict") in verdicts}


GATE_PATHS = (".agents", "AGENTS.md", ".gitignore")  # supervisor-owned; excluded from the code fingerprint
# Local client-derived data symlinks/files that must never be committed (public repo). They can sit untracked in a
# reviewed working tree, so they are excluded when comparing a reviewed tree with the committed tree.
LOCAL_DATA_PATHS = ("data/quasar_core_golden.json", "data/quasar_descriptors.sqlite", "data/evomu_sde.sqlite")
# Generated by preflight from parity results (never hand-edited); regenerated on main after a merge.
GENERATED_PATHS = ("docs/ACTION_PLAN_STATUS.md",)
DOC_EXCLUDES = ("docs/SUPERVISOR_CODER_ARCHITECTURE.md", "docs/BLOCKERS.md", "docs/OPEN_FINDINGS.md")
CODE_TREE_EXCLUDES = GATE_PATHS + LOCAL_DATA_PATHS + GENERATED_PATHS + DOC_EXCLUDES
CODE_TREE_CACHE = "code_tree_cache_v10.json"  # bump the version whenever CODE_TREE_EXCLUDES changes


def code_tree_of(root, tree, _cache={}):
    """Tree hash with the supervisor-owned gate paths removed. Two working trees with the same code tree differ
    only in .agents/ and AGENTS.md, so a review of one covers the other once the gate files match `main`."""
    if not tree:
        return ""
    if tree in _cache:
        return _cache[tree]
    cache_file = os.path.join(main_state_dir(root), CODE_TREE_CACHE)
    disk = {}
    if os.path.exists(cache_file):
        try:
            disk = json.load(open(cache_file))
        except Exception:  # noqa: BLE001
            disk = {}
    if tree in disk:
        _cache[tree] = disk[tree]
        return disk[tree]
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(d, "index"))
        if subprocess.run(["git", "read-tree", tree], cwd=root, env=env, capture_output=True).returncode:
            return ""
        subprocess.run(["git", "rm", "-r", "-f", "-q", "--cached", "--ignore-unmatch", "--"] + list(CODE_TREE_EXCLUDES),
                       cwd=root, env=env, capture_output=True)
        out = subprocess.run(["git", "write-tree"], cwd=root, env=env, capture_output=True, text=True).stdout.strip()
    _cache[tree] = out
    disk[tree] = out
    try:
        tmp = cache_file + ".tmp"
        json.dump(disk, open(tmp, "w", encoding="utf-8"))
        os.replace(tmp, cache_file)
    except OSError:
        pass
    return out


def main_state_dir(root):
    common = subprocess.run(["git", "rev-parse", "--git-common-dir"], cwd=root, capture_output=True,
                            text=True).stdout.strip()
    main_root = os.path.dirname(os.path.abspath(os.path.join(root, common))) if common else root
    p = os.path.join(main_root, STATE_DIRNAME)
    os.makedirs(p, exist_ok=True)
    return p


def worktree_roots(root):
    out = subprocess.run(["git", "worktree", "list", "--porcelain"], cwd=root, capture_output=True, text=True).stdout
    return [ln[len("worktree "):] for ln in out.splitlines() if ln.startswith("worktree ")]


# Review archive in the main checkout (2026-11-11). A track's review records live in its worktree's .evomu-reviews/,
# which disappears when the worktree is removed after landing. Every snapshot review is therefore also copied to
# <main checkout>/.evomu-reviews/review_archive/<worktree>/<timestamp>/ and indexed in review_archive/index.jsonl, so
# the evidence for what landed on main survives, and coverage/carry-over lookups still find it.
ARCHIVE_DIRNAME = "review_archive"
ARCHIVE_SKIP = ("target", "attest", "diff.patch", "parity.json")  # large and reproducible from git


def archive_review(root, rec, run_dir):
    """Copy one review's run dir and record into the main checkout's archive. Returns the archived record."""
    import shutil
    adir = os.path.join(main_state_dir(root), ARCHIVE_DIRNAME)
    dst = os.path.join(adir, os.path.basename(root), rec.get("timestamp", "unknown"))
    if run_dir and os.path.isdir(run_dir) and not os.path.exists(dst):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copytree(run_dir, dst, symlinks=True, ignore=shutil.ignore_patterns(*ARCHIVE_SKIP))
    arec = dict(rec, worktree=root, archived_at=dst)
    if rec.get("report") and run_dir:
        arec["report"] = rec["report"].replace(run_dir, dst)
    with open(os.path.join(adir, "index.jsonl"), "a", encoding="utf-8") as f:
        f.write(json.dumps(arec) + "\n")
    return arec


def archived_reviews(root):
    p = os.path.join(main_state_dir(root), ARCHIVE_DIRNAME, "index.jsonl")
    out = []
    if os.path.exists(p):
        for ln in open(p, encoding="utf-8", errors="replace"):
            try:
                r = json.loads(ln)
            except ValueError:
                continue
            if isinstance(r, dict):
                out.append(r)
    return out


def all_review_records(root):
    """Review records from every live worktree plus the archive (records of removed worktrees), each with
    'worktree' set. The same review can appear twice (live and archived); callers pick by timestamp."""
    recs = []
    for wt in worktree_roots(root):
        p = os.path.join(wt, STATE_DIRNAME, "state.json")
        if not os.path.exists(p):
            continue
        try:
            st = json.load(open(p))
        except Exception:  # noqa: BLE001
            continue
        recs.extend(dict(r, worktree=wt) for r in st.get("reviews", []) if isinstance(r, dict))
    recs.extend(archived_reviews(root))
    return recs


def working_paths_match_main(root, paths):
    """True when the working-tree content of `paths` (tracked AND untracked files, .gitignore respected) equals
    `main`. Plain `git diff main` misses untracked files, which is how gate files new on main look in a worktree
    whose branch predates them."""
    if subprocess.run(["git", "rev-parse", "--verify", "-q", "main"], cwd=root, capture_output=True).returncode:
        return False
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(d, "index"))
        subprocess.run(["git", "read-tree", "main"], cwd=root, env=env, check=True, capture_output=True)
        subprocess.run(["git", "add", "-A", "--"] + list(paths), cwd=root, env=env, capture_output=True)
        return subprocess.run(["git", "diff", "--cached", "--quiet", "main", "--"] + list(paths) +
                              [":(exclude)%s" % AUDITOR_ROWS_REL], cwd=root, env=env,
                              capture_output=True).returncode == 0


def gate_matches_main(root):
    return working_paths_match_main(root, GATE_PATHS)


def review_covering_tree(root, tree, verdicts=("PASS", "PASS_WITH_ISSUES"), mode="claims", models=None,
                         final_only=False):
    """Latest review in any worktree whose reviewed tree has the same code tree (gate paths excluded) as `tree`.
    final_only: only reviews recorded by `run_review.py --final` (FINAL_CHAIN reviewer)."""
    mine = code_tree_of(root, tree)
    if not mine:
        return None
    best = None
    for r in all_review_records(root):
        if r.get("mode", "claims") != mode or r.get("verdict") not in verdicts:
            continue
        if models and r.get("model") not in models:
            continue
        if final_only and not r.get("final"):
            continue
        if code_tree_of(root, r.get("tree")) == mine and (best is None or r.get("timestamp", "") > best.get("timestamp", "")):
            best = dict(r)
    return best


def reviewed_by_code(root, verdicts=("PASS", "PASS_WITH_ISSUES"), mode="claims", models=None, tree=None,
                     final_only=False):
    """Latest review (in ANY worktree of this repo) whose reviewed tree has the same code tree as this working
    tree, provided this tree's gate files equal `main`. Returns the review dict (plus 'worktree') or None."""
    if not gate_matches_main(root):
        return None
    return review_covering_tree(root, tree or worktree_fingerprint(root), verdicts, mode, models, final_only)


def stale_gate(root):
    """True (with a message) when this worktree's .agents/ differs from the `main` branch's copy, i.e. a track
    worktree is running an outdated review gate. auditor_rows.json is exempt (written by the orchestrator)."""
    if subprocess.run(["git", "rev-parse", "--verify", "-q", "main"], cwd=root, capture_output=True).returncode:
        return None
    if working_paths_match_main(root, [".agents"]):
        return None
    return ("this worktree's .agents/ differs from the `main` branch, so pre-flight is running older rules. Rebase "
            "onto `main` when convenient. run_review.py always reviews with main's current gate. Never edit .agents/ "
            "yourself.")


_CLAIMS_HEAD_SCAN_MAX_LINES = 60
_CLAIMS_SHA_PAREN_HEAD_RE = re.compile(
    r"`?([0-9a-fA-F]{7,40})`?\s*\(\s*(?:`?[0-9a-fA-F]{7,40}`?\s*,\s*)?`?HEAD`?\s*\)"
)
_CLAIMS_KV_RE = re.compile(r"^[*\s]*([^:\n]{1,64}?)[*\s]*:[*\s]*(.*)$")
_CLAIMS_SKIP_LABEL_PREFIX_RE = re.compile(
    r"^(?:base|merge[\s-]?base|trunk|origin/main|main|parent|upstream)\b",
    re.I,
)
_CLAIMS_SKIP_EXACT_LABELS = frozenset({
    "commits",
    "commit subject",
    "commit message",
    "diff",
    "diffstat",
    "diff size",
    "scope",
    "changed files",
    "status",
    "issue",
    "issues",
    "filter",
    "filters",
})
_CLAIMS_PURE_HEAD_LABEL_RE = re.compile(
    r"^(?:(?:branch|reviewed|current|target|tip|head)\s+)?"
    r"(?:head(?:\s+(?:commit|sha))?|commit(?:\s+sha)?|tip(?:\s+commit)?|sha)$",
    re.I,
)
_CLAIMS_LEADING_SHA_RE = re.compile(
    r"^(?:commit\s+)?[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])"
    r"(?:\s*\(\s*[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F]))?",
    re.I,
)
_CLAIMS_COMPOUND_CUTOFF_RE = re.compile(
    r"(?:origin/main|merge[\s-]?base|\b(?:rebased|based\s+on|branched\s+from|merged\s+(?:cleanly|atop|with)|commits?\s+behind)\b)",
    re.I,
)
_CLAIMS_COMPOUND_SHA_RES = (
    re.compile(r"@\s*(?:commit\s+)?[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])", re.I),
    re.compile(r"\bat\s+(?:commit\s+)?[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])", re.I),
    re.compile(r"(?:,|\()\s*commit\s+[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])", re.I),
)
_CLAIMS_OPENING_COMMIT_RE = re.compile(
    r"^Commit\s+[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])"
)
_CLAIMS_INLINE_HEAD_RE = re.compile(
    r"(?<![A-Za-z0-9_/.:-])`?(?:(?:branch|reviewed|current|target|tip)\s+)?HEAD`?"
    r"\s*(?:[:=@]|at\b|\()\s*(?:commit\s+)?[`*]*([0-9a-fA-F]{7,40})[`*]*(?![0-9a-fA-F])",
    re.I,
)
_CLAIMS_BASE_BEFORE_HEAD_RE = re.compile(r"(?:origin/main|main|base|trunk|upstream)\s*`?$", re.I)


def extract_declared_claims_head_shas(claims_text):
    """Extract explicit reviewed-HEAD commit SHA declarations from a claims markdown header.

    Matches real EvoMu claims header conventions (`HEAD: <sha>`, `Branch HEAD: <sha>`,
    `Reviewed HEAD: <sha>`, `Head Commit: <sha>`, `Tip Commit: <sha>`, `Commit: <sha>`,
    `Branch / Commit: <branch> @ <sha>`, `Branch / HEAD: <branch> at <sha>`,
    `` `<sha>` (`HEAD`) ``, and opening `Commit <sha> ...`) while ignoring base/merge-base/
    `origin/main` SHAs and historical body references.

    Returns a deduplicated list of `(line_no, sha, raw_line)` tuples.
    """
    found = []
    seen = set()
    in_fence = False

    def _add(lineno, sha, raw_line):
        low = sha.lower()
        if low not in seen:
            seen.add(low)
            found.append((lineno, sha, raw_line))

    for lineno, raw_line in enumerate(claims_text.splitlines()[:_CLAIMS_HEAD_SCAN_MAX_LINES], 1):
        stripped = raw_line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence or not stripped:
            continue
        clean = re.sub(r"^[-*•]\s+", "", stripped)

        # 1. Explicit `<sha> (HEAD)` or `<sha> (<short>, HEAD)` tag (highest specificity).
        paren_matches = list(_CLAIMS_SHA_PAREN_HEAD_RE.finditer(clean))
        if paren_matches:
            for pm in paren_matches:
                _add(lineno, pm.group(1), raw_line)
            continue

        # 2. Key: Value metadata lines.
        m_kv = _CLAIMS_KV_RE.match(clean)
        if m_kv:
            label = re.sub(r"[*_`]+", "", m_kv.group(1)).strip().lower()
            rest = m_kv.group(2).strip()
            if _CLAIMS_SKIP_LABEL_PREFIX_RE.match(label) or label in _CLAIMS_SKIP_EXACT_LABELS:
                continue
            if _CLAIMS_PURE_HEAD_LABEL_RE.match(label):
                m_sha = _CLAIMS_LEADING_SHA_RE.match(rest)
                if m_sha:
                    s1, s2 = m_sha.group(1), m_sha.group(2)
                    chosen = s2 if (s2 and len(s2) > len(s1) and s2.lower().startswith(s1.lower())) else s1
                    _add(lineno, chosen, raw_line)
                continue
            if "branch" in label or "worktree" in label:
                cut = _CLAIMS_COMPOUND_CUTOFF_RE.search(rest)
                branch_part = rest[:cut.start()] if cut else rest
                matched_compound = False
                for rx in _CLAIMS_COMPOUND_SHA_RES:
                    mc = rx.search(branch_part)
                    if mc:
                        _add(lineno, mc.group(1), raw_line)
                        matched_compound = True
                        break
                if matched_compound:
                    continue

        # 3. Un-bulleted opening prose paragraph `Commit <sha> (...)` when no header declared HEAD yet.
        if not found and lineno <= 10 and not stripped.startswith(("-", "*", "•")):
            m_open = _CLAIMS_OPENING_COMMIT_RE.match(re.sub(r"^\*\*|\*\*$", "", clean))
            if m_open:
                _add(lineno, m_open.group(1), raw_line)
                continue

        # 4. Fallback inline `HEAD: <sha>` / `HEAD (<sha>)` / `HEAD @ <sha>` (excluding `origin/main HEAD`).
        for mi in _CLAIMS_INLINE_HEAD_RE.finditer(clean):
            before = clean[:mi.start()]
            if _CLAIMS_BASE_BEFORE_HEAD_RE.search(before):
                continue
            _add(lineno, mi.group(1), raw_line)

    return found


def check_claims_head_sha(root, claims_path, target_commit="HEAD"):
    """Verify any HEAD commit SHA explicitly declared in `claims_path` matches `target_commit`.

    Returns `[]` when `claims_path` is missing, unreadable, or declares no HEAD SHA, or when all
    declared SHAs prefix-match `git rev-parse --verify <target_commit>^{commit}` (case-insensitive).
    Otherwise returns `[("CLAIMS_STALE_HEAD_SHA", msg, claims_path, lineno), ...]`.
    """
    if not claims_path or not os.path.isfile(claims_path):
        return []
    proc = subprocess.run(
        ["git", "rev-parse", "--verify", str(target_commit) + "^{commit}"],
        cwd=root,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0 or not proc.stdout.strip():
        return []
    expected = proc.stdout.strip().lower()
    try:
        with open(claims_path, encoding="utf-8", errors="replace") as fh:
            claims_text = fh.read()
    except OSError:
        return []
    declared = extract_declared_claims_head_shas(claims_text)
    if not declared:
        return []
    violations = []
    for lineno, decl_sha, _ in declared:
        if not expected.startswith(decl_sha.lower()):
            violations.append((
                "CLAIMS_STALE_HEAD_SHA",
                "Claims file declares reviewed HEAD `%s` (line %d), but `%s` resolves to `%s` (`%s`). "
                "Update the claims file's HEAD SHA to match the current commit before running preflight or run_review.py."
                % (decl_sha, lineno, target_commit, expected[:12], expected),
                claims_path,
                lineno,
            ))
    return violations


